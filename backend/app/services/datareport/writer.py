class ReportWriter:
    def __init__(self, target: str | io.BytesIO, ctx: ReportContext, *, brand: str = BRAND) -> None:
        self.ctx = ctx
        self.t = ctx.t
        self.brand = brand
        self.wb = xlsxwriter.Workbook(
            target,
            {
                "constant_memory": True,
                "strings_to_numbers": False,
                "strings_to_formulas": False,
                "strings_to_urls": False,
                "nan_inf_to_errors": False,
                "remove_timezone": True,
                "default_format_properties": {"font_name": FONT, "font_size": 10},
            },
        )
        self.wb.worksheet_class = SharedStringSheet
        self.wb.set_properties(
            {
                "title": f"{ctx.portal_name} · {ctx.folder_name}",
                "subject": self.text("cover.title"),
                "author": ctx.generated_by or ctx.portal_name,
                "company": ctx.portal_name,
                "comments": f"{self.text('cover.data_version')}: {ctx.data_version}",
            }
        )
        self._formats: dict[tuple[Any, ...], Any] = {}
        self._status_formats: list[tuple[tuple[str, ...], Any]] = []
        self._used_titles: set[str] = set()
        self._tables = 0
        self.links = 0
        self.summaries: list[SheetSummary] = []
        self.cover_title = sheet_title(self.text("sheet.overview"), self._used_titles)
        self.cover = self.wb.add_worksheet(self.cover_title)
        self.cover.hide_gridlines(2)
        self.cover.set_tab_color(f"#{self.brand}")
        self._current: _SheetState | None = None

    def text(self, key: str, **values: Any) -> str:
        default = TEXT.get(key, key)
        out = self.t(key, default) or default
        if values:
            try:
                return out.format(**values)
            except (KeyError, IndexError, ValueError):
                return default.format(**values)
        return out

    def fmt(self, *key: Any, **props: Any) -> Any:
        cache_key = (*key, tuple(sorted(props.items())))
        found = self._formats.get(cache_key)
        if found is None:
            base = {"font_name": FONT, "font_size": 10, "font_family": FONT_FAMILY, "valign": "top"}
            base.update(props)
            found = self.wb.add_format(base)
            self._formats[cache_key] = found
        return found

    def cell_format(self, kind: str, row_kind: str, wrap: bool) -> Any:
        props: dict[str, Any] = {}
        number = NUM_FORMATS.get(kind)
        if number:
            props["num_format"] = number
        if kind in ("date", "datetime"):
            props["align"] = "left"
        elif kind == "duration_ms":
            props["align"] = "right"
        elif kind == "link":
            props["font_color"] = self.brand
            props["underline"] = 1
        elif kind in ("id", "url"):
            props["font_color"] = MUTED
            props["font_size"] = 9
        elif kind == "bool":
            props["align"] = "center"
        elif kind == "status":
            props["bold"] = True
        if wrap or kind in ("longtext", "json"):
            props["text_wrap"] = True
        if row_kind in ("translation", "summary_translation"):
            props["italic"] = True
            if kind != "link":
                props["font_color"] = MUTED
            props["indent"] = 1 if kind in ("text", "longtext") else 0
        elif row_kind == "summary":
            props["bold"] = True
            props["bg_color"] = BRAND_SOFT
        if row_kind == "summary_translation":
            props["bg_color"] = BRAND_SOFT
        return self.fmt("cell", kind, row_kind, wrap, **props)

    def run_format(self, row_kind: str, bold: bool) -> Any:
        props: dict[str, Any] = {"font_color": INK}
        if bold:
            props["bold"] = True
        if row_kind in ("translation", "summary_translation"):
            props["italic"] = True
            if not bold:
                props["font_color"] = MUTED
        return self.fmt("run", row_kind, bold, **props)

    def status_formats(self) -> list[tuple[tuple[str, ...], Any]]:
        if not self._status_formats:
            for words, keys, (bg, fg) in ((RED_WORDS, RED_KEYS, RED), (AMBER_WORDS, AMBER_KEYS, AMBER), (GREEN_WORDS, GREEN_KEYS, GREEN)):
                local = [self.t(f"status.{k}", "") for k in keys]
                extra = [w.split("{")[0].strip(" :") for w in local if w]
                chosen = tuple(dict.fromkeys(w.replace('"', "") for w in (*words, *extra) if w and len(w) > 1))
                self._status_formats.append((chosen, self.wb.add_format({"bg_color": f"#{bg}", "font_color": f"#{fg}"})))
        return self._status_formats

    def header_format(self) -> Any:
        return self.fmt(
            "header",
            bold=True,
            font_color="FFFFFF",
            bg_color=self.brand,
            text_wrap=True,
            valign="vcenter",
            border=1,
            border_color=self.brand,
        )

    def url(self, ws: Any, row: int, col: int, url: str, fmt: Any, *, string: str) -> None:
        self.links += 1
        ws.write_url(row, col, url, fmt, string=string)

    def link_allowance(self) -> int:
        return max(0, min(LINKS_PER_SHEET, LINKS_PER_BOOK - LINK_RESERVE - self.links))

    def arrange(self, sheet: Sheet, bundle_url: str | None) -> tuple[list[Column], int | None, bool]:
        spark_members = {c.key for c in sheet.columns if c.group and c.group in sheet.sparkline_columns}
        tech = [c for c in sheet.columns if technical(c) and c.key not in spark_members]
        if len(tech) == len(sheet.columns):
            tech = []
        main = [c for c in sheet.columns if c not in tech]
        link_cols = [c for c in main if c.kind == "link"]
        rows = sheet.count
        if rows is None and isinstance(sheet.rows, (list, tuple)):
            rows = len(sheet.rows)
        bound = sheet.link_bound if sheet.link_bound is not None else (None if rows is None else rows * len(link_cols))
        fixed = 1 + (1 if bundle_url and sheet.media_ids else 0) + sum(1 for b in sheet.banners[:3] if b.url)
        url_text = bool(link_cols) and (bound is None or bound > self.link_allowance() - fixed)
        if url_text:
            widened: list[Column] = []
            for c in main:
                widened.append(c)
                if c.kind == "link":
                    label = self.t(f"col.{sheet.key}.{c.key}", c.label)
                    widened.append(Column(c.key + URL_SUFFIX, self.text("col.webAddress", label=label), "text", self.text("dict.webAddress", label=label), width=36, tech=False))
            main = widened
        return main + tech, (len(main) if tech else None), url_text

    def begin(self, sheet: Sheet, *, bundle_url: str | None) -> _SheetState:
        if self._current is not None:
            raise RuntimeError("finish the previous sheet first")
        local_name = self.t(f"sheet.{sheet.key}", sheet.name)
        title = sheet_title(local_name, self._used_titles)
        ws = self.wb.add_worksheet(title)
        ws.set_tab_color(f"#{(sheet.color or self.brand).lstrip('#')}")
        ws.hide_gridlines(2)
        columns, tech_from, url_text = self.arrange(sheet, bundle_url)
        labels = _unique([clean(self.t(f"col.{sheet.key}.{c.key}", c.label)).replace("\n", " ").strip() or c.key for c in columns])
        prepared = _Prepared(
            columns=columns,
            labels=labels,
            widths=[float(max(c.width or DEFAULT_WIDTH.get(c.kind, 18), 6)) for c in columns],
            tech_from=tech_from,
            url_text=url_text,
        )
        spark_keys = [k for k in sheet.sparkline_columns if any(c.key == k for c in sheet.columns)]
        state = _SheetState(self, ws, sheet, title, prepared, bundle_url, spark_keys)
        state.start()
        self._current = state
        return state

    def end(self, state: _SheetState) -> SheetSummary:
        summary = state.finish()
        self.summaries.append(summary)
        self._current = None
        return summary

    def table_name(self, key: str) -> str:
        self._tables += 1
        base = _TABLE_BAD.sub("_", key)[:200] or "Data"
        return f"tbl_{base}_{self._tables}"

    def write_dictionary(self) -> None:
        title = sheet_title(self.text("sheet.dictionary"), self._used_titles)
        ws = self.wb.add_worksheet(title)
        ws.hide_gridlines(2)
        ws.set_tab_color(f"#{MUTED}")
        ws.write_string(0, 0, clean(self.text("dict.title")), self.fmt("h1", bold=True, font_size=16, font_color=self.brand))
        self.url(ws, 1, 0, f"internal:'{self.cover_title}'!A1", self.fmt("backlink", font_color=self.brand, underline=1), string=clean(self.text("link.back")))
        headers = _unique([clean(self.text(k)) for k in ("dict.heading.sheet", "dict.heading.column", "dict.heading.kind", "dict.heading.description", "dict.heading.source")])
        top = 3
        for col, label in enumerate(headers):
            ws.write_string(top, col, label, self.header_format())
        row = top
        body = self.fmt("dict", text_wrap=True)
        for summary in self.summaries:
            for column in summary.columns:
                row += 1
                ws.write_string(row, 0, clean(summary.title), body)
                ws.write_string(row, 1, clean(self.t(f"col.{summary.key}.{column.key}", column.label)), body)
                ws.write_string(row, 2, clean(self.text(f"dict.kind.{column.kind}")), body)
                ws.write_string(row, 3, clean(self.t(f"dict.{summary.key}.{column.key}", column.description) if column.description else ""), body)
                ws.write_string(row, 4, clean(column.source or ""), self.fmt("dict_src", font_color=MUTED, font_size=9, text_wrap=True))
        widths = (24, 28, 18, 70, 36)
        for col, width in enumerate(widths):
            ws.set_column(col, col, width)
        if row > top:
            self._table(ws, top, 0, row, len(headers) - 1, headers, "Dictionary")
        ws.freeze_panes(top + 1, 0)
        self._print_setup(ws, top, title)

    def _table(self, ws: Any, first_row: int, first_col: int, last_row: int, last_col: int, headers: list[str], key: str, totals: dict[int, str] | None = None, total_label: str | None = None) -> None:
        columns: list[dict[str, Any]] = []
        for index, header in enumerate(headers):
            spec: dict[str, Any] = {"header": header}
            if totals and index in totals:
                spec["total_function"] = totals[index]
            elif totals and index == 0 and total_label:
                spec["total_string"] = total_label
            columns.append(spec)
        options: dict[str, Any] = {
            "name": self.table_name(key),
            "style": TABLE_STYLE,
            "columns": columns,
            "autofilter": True,
            "banded_rows": True,
        }
        if totals:
            options["total_row"] = True
        streamed_table(ws, first_row, first_col, last_row, last_col, options)

    def _print_setup(self, ws: Any, header_row: int | None, title: str) -> None:
        ws.set_landscape()
        ws.set_paper(9)
        ws.fit_to_pages(1, 0)
        ws.set_margins(left=0.4, right=0.4, top=0.6, bottom=0.6)
        if header_row is not None:
            ws.repeat_rows(header_row)
        stamp = _header_text(self.ctx.generated_at[:16].replace("T", " "))
        header = self.text("print.header", portal=_header_text(self.ctx.portal_name), title=_header_text(title))
        footer = self.text("print.footer", date=stamp, portal=_header_text(self.ctx.portal_name), title=_header_text(title))
        ws.set_header(header[:250])
        ws.set_footer(footer[:250])

