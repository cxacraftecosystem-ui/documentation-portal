    def _table(self, ws: Any, first_row: int, first_col: int, last_row: int, last_col: int, headers: list[str], key: str, totals: dict[int, str] | None = None, total_label: str | None = None) -> None:
        columns: list[dict[str, Any]] = []
        for index, header in enumerate(headers):
            spec: dict[str, Any] = {"header": header}
            if totals and index in totals:
                spec["total_function"] = totals[index]
            elif totals and index == 0 and total_label:
                spec["total_string"] = total_label
            columns.append(spec)
        options: dict[str, Any] = {
            "name": self.table_name(key),
            "style": TABLE_STYLE,
            "columns": columns,
            "autofilter": True,
            "banded_rows": True,
        }
        if totals:
            options["total_row"] = True
        streamed_table(ws, first_row, first_col, last_row, last_col, options)

