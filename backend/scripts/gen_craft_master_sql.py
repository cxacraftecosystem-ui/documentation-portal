"""Write the craft master list migration from ``app/data/craft_master_list.json`` (docs/CRAFTS.md).

The migration's SQL is generated, so it cannot drift from the file it seeds: ``--check`` (run by
``tests/test_craft_master_migration.py``) fails when the committed SQL is not what this prints. The
output is the same text in both portals; the designer portal's two extra columns are added inside a
guard that does nothing where their tables do not exist.

    cd backend && .venv/Scripts/python.exe -m scripts.gen_craft_master_sql           # write
    cd backend && .venv/Scripts/python.exe -m scripts.gen_craft_master_sql --check   # compare
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from app.services import craft_master  # noqa: E402
from app.services.cross_portal_codes import SQL_ACCENTS_FROM, SQL_ACCENTS_TO  # noqa: E402

MIGRATION_NAME = "20261104090000_craft_master_list"
MIGRATION = BACKEND / "prisma" / "migrations" / MIGRATION_NAME / "migration.sql"


def literal(value: object) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def array(values: tuple[str, ...] | list[str]) -> str:
    if not values:
        return "ARRAY[]::TEXT[]"
    return "ARRAY[" + ", ".join(literal(v) for v in values) + "]::TEXT[]"


HEADER = """-- THE CRAFT MASTER LIST (2026-10-20). See docs/CRAFTS.md.
--
-- GENERATED by backend/scripts/gen_craft_master_sql.py from backend/app/data/craft_master_list.json.
-- Do not edit by hand: change the generator and run it. The text is the same in both portals.
--
-- 1. The two enums and the two taxonomy tables, and the new Craft columns.
-- 2. Every craft that exists before this migration becomes LEGACY: waiting for
--    `python -m app.scripts.map_crafts` to promote, merge or adopt it (docs/RELEASE.md).
-- 3. The 9 categories, 36 sub-categories and 455 crafts, with ids derived from their slugs.
-- 4. The pre-existing rows get a slug by the naming helper's field() rule (-2, -3 on a collision,
--    in createdAt, id order), and a seeded craft whose name is a known spelling gets its shared code.
-- 5. Designer portal only: DesignWorkshop.craftId and AnnualPlanEntry.craftId.

CREATE TYPE "GiStatus" AS ENUM ('GI', 'NON_GI');

CREATE TYPE "CraftStatus" AS ENUM ('ACTIVE', 'LEGACY', 'MERGED');

CREATE TABLE "CraftCategory" (
    "id" TEXT NOT NULL,
    "slug" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "sortOrder" INTEGER NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    "createdById" TEXT,

    CONSTRAINT "CraftCategory_pkey" PRIMARY KEY ("id")
);

CREATE TABLE "CraftSubCategory" (
    "id" TEXT NOT NULL,
    "slug" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "categoryId" TEXT NOT NULL,
    "sortOrder" INTEGER NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    "createdById" TEXT,

    CONSTRAINT "CraftSubCategory_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX "CraftCategory_slug_key" ON "CraftCategory"("slug");
CREATE UNIQUE INDEX "CraftCategory_name_key" ON "CraftCategory"("name");
CREATE UNIQUE INDEX "CraftSubCategory_slug_key" ON "CraftSubCategory"("slug");
CREATE INDEX "CraftSubCategory_categoryId_idx" ON "CraftSubCategory"("categoryId");
CREATE UNIQUE INDEX "CraftSubCategory_categoryId_name_key" ON "CraftSubCategory"("categoryId", "name");

ALTER TABLE "CraftSubCategory" ADD CONSTRAINT "CraftSubCategory_categoryId_fkey" FOREIGN KEY ("categoryId") REFERENCES "CraftCategory"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- A craft name is unique within its sub-category now, not across the whole list.
DROP INDEX "Craft_name_key";

ALTER TABLE "Craft" ADD COLUMN "slug" TEXT,
ADD COLUMN "subCategoryId" TEXT,
ADD COLUMN "sourceSerial" INTEGER,
ADD COLUMN "stateOfOrigin" TEXT[] DEFAULT ARRAY[]::TEXT[],
ADD COLUMN "stateOfPractice" TEXT[] DEFAULT ARRAY[]::TEXT[],
ADD COLUMN "giStatus" "GiStatus",
ADD COLUMN "isCatchAll" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN "sourceNotes" TEXT[] DEFAULT ARRAY[]::TEXT[],
ADD COLUMN "status" "CraftStatus" NOT NULL DEFAULT 'ACTIVE',
ADD COLUMN "mergedIntoId" TEXT;

-- 2. Everything already here waits for the mapping script.
UPDATE "Craft" SET "status" = 'LEGACY';

CREATE UNIQUE INDEX "Craft_slug_key" ON "Craft"("slug");
CREATE UNIQUE INDEX "Craft_sourceSerial_key" ON "Craft"("sourceSerial");
"""

FOOTER = f"""
-- 4. A slug for every row that existed before: words of the name, accents folded, punctuation
-- dropped, each word Title-Cased unless it holds a digit or is a 2-3 letter upper-case code, joined
-- by '-'. A taken slug gets -2, -3 ... in createdAt, id order.
WITH "words" AS (
    SELECT c."id", w."word", w."n"
    FROM "Craft" c
    CROSS JOIN LATERAL regexp_split_to_table(
        translate(c."name", {literal(SQL_ACCENTS_FROM)}, {literal(SQL_ACCENTS_TO)}),
        '[^A-Za-z0-9]+'
    ) WITH ORDINALITY AS w("word", "n")
    WHERE c."slug" IS NULL AND w."word" <> ''
), "bases" AS (
    SELECT c."id", c."createdAt",
        COALESCE(
            (SELECT string_agg(
                CASE
                    WHEN w."word" ~ '[0-9]' THEN w."word"
                    WHEN length(w."word") BETWEEN 2 AND 3 AND w."word" ~ '^[A-Z]+$' THEN w."word"
                    ELSE upper(left(w."word", 1)) || lower(substr(w."word", 2))
                END, '-' ORDER BY w."n")
             FROM "words" w WHERE w."id" = c."id"),
            'Craft'
        ) AS "base"
    FROM "Craft" c
    WHERE c."slug" IS NULL
), "ranked" AS (
    SELECT b."id", b."base",
        row_number() OVER (PARTITION BY b."base" ORDER BY b."createdAt", b."id")
        + CASE WHEN EXISTS (SELECT 1 FROM "Craft" s WHERE s."slug" = b."base") THEN 1 ELSE 0 END AS "n"
    FROM "bases" b
)
UPDATE "Craft" c
SET "slug" = CASE WHEN r."n" = 1 THEN r."base" ELSE r."base" || '-' || r."n" END
FROM "ranked" r
WHERE c."id" = r."id";

ALTER TABLE "Craft" ALTER COLUMN "slug" SET NOT NULL;

-- A row written without a slug (a raw INSERT, a one-off script) still gets a unique one. The routes and
-- the seed always write a naming slug; this default is the schema's `@default(dbgenerated(...))`.
ALTER TABLE "Craft" ALTER COLUMN "slug" SET DEFAULT ('craft-'::text || md5((random())::text || (clock_timestamp())::text));

-- A seeded craft whose name is a known spelling takes that shared code (C26), as a new craft would.
UPDATE "Craft" c
SET "craftCode" = sp."craftCode"
FROM "CraftSpelling" sp
WHERE c."craftCode" IS NULL
  AND c."sourceSerial" IS NOT NULL
  AND sp."spelling" = btrim(regexp_replace(translate(lower(c."name"), {literal(SQL_ACCENTS_FROM)}, {literal(SQL_ACCENTS_TO)}), '[^a-z0-9]+', ' ', 'g'));

CREATE INDEX "Craft_subCategoryId_idx" ON "Craft"("subCategoryId");
CREATE INDEX "Craft_status_idx" ON "Craft"("status");
CREATE UNIQUE INDEX "Craft_subCategoryId_name_key" ON "Craft"("subCategoryId", "name");

ALTER TABLE "Craft" ADD CONSTRAINT "Craft_subCategoryId_fkey" FOREIGN KEY ("subCategoryId") REFERENCES "CraftSubCategory"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
ALTER TABLE "Craft" ADD CONSTRAINT "Craft_mergedIntoId_fkey" FOREIGN KEY ("mergedIntoId") REFERENCES "Craft"("id") ON DELETE SET NULL ON UPDATE CASCADE;

-- 5. Designer portal only. The Field Repository has neither table, so the guard skips both.
DO $$
BEGIN
    IF to_regclass('"DesignWorkshop"') IS NOT NULL THEN
        ALTER TABLE "DesignWorkshop" ADD COLUMN IF NOT EXISTS "craftId" TEXT;
        CREATE INDEX IF NOT EXISTS "DesignWorkshop_craftId_idx" ON "DesignWorkshop"("craftId");
        ALTER TABLE "DesignWorkshop" ADD CONSTRAINT "DesignWorkshop_craftId_fkey" FOREIGN KEY ("craftId") REFERENCES "Craft"("id") ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
    IF to_regclass('"AnnualPlanEntry"') IS NOT NULL THEN
        ALTER TABLE "AnnualPlanEntry" ADD COLUMN IF NOT EXISTS "craftId" TEXT;
        CREATE INDEX IF NOT EXISTS "AnnualPlanEntry_craftId_idx" ON "AnnualPlanEntry"("craftId");
        ALTER TABLE "AnnualPlanEntry" ADD CONSTRAINT "AnnualPlanEntry_craftId_fkey" FOREIGN KEY ("craftId") REFERENCES "Craft"("id") ON DELETE SET NULL ON UPDATE CASCADE;
    END IF;
END $$;
"""


def render() -> str:
    lines: list[str] = [HEADER]
    lines.append("-- 3. The master list.")
    lines.append('INSERT INTO "CraftCategory" ("id", "slug", "name", "sortOrder", "updatedAt") VALUES')
    categories = craft_master.master_categories()
    lines.append(
        ",\n".join(
            f"    ({literal(craft_master.master_id('k', c.slug))}, {literal(c.slug)}, {literal(c.name)}, "
            f"{c.sort_order}, CURRENT_TIMESTAMP)"
            for c in categories
        )
    )
    lines.append('ON CONFLICT ("slug") DO NOTHING;')
    lines.append("")
    lines.append(
        'INSERT INTO "CraftSubCategory" ("id", "slug", "name", "categoryId", "sortOrder", "updatedAt") VALUES'
    )
    lines.append(
        ",\n".join(
            f"    ({literal(craft_master.master_id('s', s.slug))}, {literal(s.slug)}, {literal(s.name)}, "
            f"{literal(craft_master.master_id('k', c.slug))}, {s.sort_order}, CURRENT_TIMESTAMP)"
            for c in categories
            for s in c.sub_categories
        )
    )
    lines.append('ON CONFLICT ("slug") DO NOTHING;')
    lines.append("")
    lines.append(
        'INSERT INTO "Craft" ("id", "name", "slug", "subCategoryId", "category", "sourceSerial", '
        '"stateOfOrigin", "stateOfPractice", "giStatus", "isCatchAll", "sourceNotes", "status", '
        '"updatedAt") VALUES'
    )
    lines.append(
        ",\n".join(
            f"    ({literal(craft_master.master_id('c', r.slug))}, {literal(r.name)}, {literal(r.slug)}, "
            f"{literal(craft_master.master_id('s', r.sub_category_slug))}, {literal(r.category)}, "
            f"{r.source_serial}, {array(r.state_of_origin)}, {array(r.state_of_practice)}, "
            f"'{r.gi_status}', {literal(r.is_catch_all)}, {array(r.notes)}, 'ACTIVE', CURRENT_TIMESTAMP)"
            for r in craft_master.load_master()
        )
    )
    lines.append('ON CONFLICT ("slug") DO NOTHING;')
    lines.append(FOOTER)
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Write or check the craft master list migration.")
    parser.add_argument("--check", action="store_true", help="fail when the committed SQL differs")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = MIGRATION.read_text(encoding="utf-8").replace("\r\n", "\n") if MIGRATION.is_file() else ""
        if current != text:
            print(f"{MIGRATION} is not what the generator writes; run it without --check.")
            return 1
        print("up to date")
        return 0
    MIGRATION.parent.mkdir(parents=True, exist_ok=True)
    MIGRATION.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {MIGRATION}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
