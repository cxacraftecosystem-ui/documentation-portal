"""The master craft list migration equals the file it seeds (docs/CRAFTS.md).

The SQL is generated by ``scripts/gen_craft_master_sql.py``; the first tests prove the committed text
is what the generator writes and that it carries every row. The last one reads a migrated database
(skipped without a local one) and checks the rows themselves. The same file in both portals.
"""

from __future__ import annotations

import asyncio
import os
from collections import Counter

import pytest

from app.services import craft_master as cm
from scripts import gen_craft_master_sql as gen

_URL = os.environ.get("DATABASE_URL", "")
_LOCAL = any(host in _URL for host in ("localhost", "127.0.0.1"))


def _sql() -> str:
    return gen.MIGRATION.read_text(encoding="utf-8").replace("\r\n", "\n")


def test_the_committed_migration_is_what_the_generator_writes():
    assert _sql() == gen.render(), "run: python -m scripts.gen_craft_master_sql"


def test_the_migration_seeds_every_row_of_the_file():
    sql = _sql()
    for craft in cm.load_master():
        row = (
            f"({gen.literal(cm.master_id('c', craft.slug))}, {gen.literal(craft.name)}, {gen.literal(craft.slug)}, "
            f"{gen.literal(cm.master_id('s', craft.sub_category_slug))}, {gen.literal(craft.category)}, "
            f"{craft.source_serial}, {gen.array(craft.state_of_origin)}, {gen.array(craft.state_of_practice)}, "
            f"'{craft.gi_status}', "
        )
        assert row in sql, craft.slug
    for category in cm.master_categories():
        assert f"({gen.literal(cm.master_id('k', category.slug))}, {gen.literal(category.slug)}" in sql
        for sub in category.sub_categories:
            assert f"({gen.literal(cm.master_id('s', sub.slug))}, {gen.literal(sub.slug)}" in sql


def test_the_migration_keeps_every_existing_craft():
    sql = _sql()
    upper = sql.upper()
    assert "DELETE FROM" not in upper and "DROP TABLE" not in upper and "DROP COLUMN" not in upper
    assert 'UPDATE "Craft" SET "status" = \'LEGACY\';' in sql
    assert sql.count('ON CONFLICT ("slug") DO NOTHING') == 3


@pytest.mark.skipif(not _LOCAL, reason="needs a LOCAL database; refuses to run against a remote DATABASE_URL")
def test_the_migrated_database_holds_the_list():
    from app.core.db import db

    async def read() -> tuple[list, list, list]:
        await db.connect()
        try:
            crafts = await db.craft.find_many(where={"sourceSerial": {"not": None}})
            subs = await db.craftsubcategory.find_many()
            cats = await db.craftcategory.find_many()
            return crafts, subs, cats
        finally:
            await db.disconnect()

    crafts, subs, cats = asyncio.run(read())
    by_serial = {c.sourceSerial: c for c in crafts}
    assert len(by_serial) == 455
    assert {s.slug for s in subs} >= {s.slug for c in cm.master_categories() for s in c.sub_categories}
    assert {c.slug for c in cats} >= {c.slug for c in cm.master_categories()}
    assert Counter(str(getattr(c.giStatus, "value", c.giStatus)) for c in crafts) == {"GI": 209, "NON_GI": 246}
    for master in cm.load_master():
        row = by_serial[master.source_serial]
        assert row.slug == master.slug
        assert list(row.stateOfOrigin) == list(master.state_of_origin)
        assert list(row.stateOfPractice) == list(master.state_of_practice)
        assert row.category == master.category
