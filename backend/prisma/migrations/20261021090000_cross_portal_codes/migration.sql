-- C26: SHARED CRAFT AND QUESTION CODES, seeded from app/data/cross_portal_codes.json.
--
-- ADDITIVE AND SAFE ON A LIVE DATABASE. Two new tables, one nullable column on "Craft" and one on
-- each question table, each with an index. No existing value is changed except the new columns,
-- which start NULL and are filled only where a craft's name or a question's section and wording
-- matches the shared file EXACTLY after folding (lower case, accents folded, punctuation and spaces
-- to one space). A row that matches nothing keeps NULL and behaves as before; nothing is guessed.
--
-- Every statement is guarded (IF NOT EXISTS / ON CONFLICT / IS NULL), so a re-run changes nothing.
-- The folding expression below is the one app/services/cross_portal_codes.sql_normalise_emulation
-- spells in Python; tests/test_cross_portal_codes.py proves the two agree on every spelling and
-- prompt in the file. The values were generated from the file; the test also checks they match it.

CREATE TABLE IF NOT EXISTS "CraftCode" (
    "code" TEXT NOT NULL,
    "name" TEXT NOT NULL,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL,
    CONSTRAINT "CraftCode_pkey" PRIMARY KEY ("code")
);

CREATE TABLE IF NOT EXISTS "CraftSpelling" (
    "spelling" TEXT NOT NULL,
    "label" TEXT NOT NULL,
    "craftCode" TEXT NOT NULL,
    "source" TEXT NOT NULL DEFAULT 'SHARED',
    "createdById" TEXT,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT "CraftSpelling_pkey" PRIMARY KEY ("spelling")
);

CREATE INDEX IF NOT EXISTS "CraftSpelling_craftCode_idx" ON "CraftSpelling"("craftCode");

DO $$ BEGIN
    ALTER TABLE "CraftSpelling" ADD CONSTRAINT "CraftSpelling_craftCode_fkey"
        FOREIGN KEY ("craftCode") REFERENCES "CraftCode"("code") ON DELETE CASCADE ON UPDATE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

ALTER TABLE "Craft" ADD COLUMN IF NOT EXISTS "craftCode" TEXT;
CREATE INDEX IF NOT EXISTS "Craft_craftCode_idx" ON "Craft"("craftCode");

DO $$ BEGIN
    ALTER TABLE "Craft" ADD CONSTRAINT "Craft_craftCode_fkey"
        FOREIGN KEY ("craftCode") REFERENCES "CraftCode"("code") ON DELETE SET NULL ON UPDATE CASCADE;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

ALTER TABLE "QuestionnaireQuestion" ADD COLUMN IF NOT EXISTS "questionCode" TEXT;
CREATE INDEX IF NOT EXISTS "QuestionnaireQuestion_questionCode_idx" ON "QuestionnaireQuestion"("questionCode");

