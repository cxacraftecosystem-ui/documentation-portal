def ident_char(c):
    return c.isalnum() or c == "_" or c == "$"


def line_table(text):
    rows = []
    i = 0
    n = len(text)
    while i < n:
        j = text.find("\n", i)
        if j < 0:
            rows.append((i, n, n))
            break
        ce = j - 1 if j > i and text[j - 1] == "\r" else j
        rows.append((i, ce, j + 1))
        i = j + 1
    return rows


def is_plain_js(path):
    return path.endswith((".js", ".jsx", ".mjs", ".cjs"))


def comment_lines(raw):
    if raw.startswith("/*"):
        body = raw[2:-2] if raw.endswith("*/") and len(raw) >= 4 else raw[2:]
    elif raw.startswith("<!--"):
        body = raw[4:-3] if raw.endswith("-->") and len(raw) >= 7 else raw[4:]
    elif raw.startswith(("//", "--")):
        body = raw[2:]
    else:
        body = raw
    lines = [line.strip().lstrip("*").strip() for line in body.splitlines()]
    return lines or [""]


def keeps(lang, raw, start, path):
    if LICENSE.search(raw):
        return True
    if start == 0 and raw.startswith("#!"):
        return True
    if lang in JS_LANGS:
        if raw.startswith("/*!"):
            return True
        if raw.startswith("///"):
            rest = raw[3:].lstrip()
            if rest.startswith(("<reference", "<amd-")):
                return True
        plain = is_plain_js(path)
        for line in comment_lines(raw):
            if JS_DIRECTIVE.match(line):
                return True
            if plain and JS_TYPES.match(line):
                return True
            if plain and raw.startswith("/*") and JS_GLOBALS.match(line):
                return True
        return False
    if lang in ("kotlin", "java"):
        return any(KT_DIRECTIVE.match(line) for line in comment_lines(raw))
    if lang == "css":
        if raw.startswith("/*!"):
            return True
        return any(CSS_DIRECTIVE.match(line) for line in comment_lines(raw))
    if lang == "sql":
        return any(SQL_DIRECTIVE.match(line) for line in comment_lines(raw))
    if lang == "xml":
        return any(XML_DIRECTIVE.match(line) for line in comment_lines(raw))
    if lang == "shell":
        return bool(SH_DIRECTIVE.match(raw))
    if lang == "yaml":
        return bool(YAML_DIRECTIVE.match(raw) or SH_DIRECTIVE.match(raw))
    if lang == "toml":
        return bool(TOML_DIRECTIVE.match(raw))
    if lang == "dockerfile":
        return bool(DOCKER_DIRECTIVE.match(raw))
    return False


class Scan:
    def __init__(self, text, lang, path=""):
        self.t = text
        self.n = len(text)
        self.lang = lang
        self.path = path
        self.out = Lexed()
        self.jsx = lang in ("tsx", "jsx")
        self.ts = lang in ("ts", "tsx")

    def comment(self, s, e, kind, keep=None):
        raw = self.t[s:e]
        cm = Comment(s, e, kind=kind, keep=keeps(self.lang, raw, s, self.path) if keep is None else keep)
        self.out.comments.append(cm)
        return cm

    def literal(self, s, e):
        if e > s:
            self.out.literals.append((s, e))

    def line_end(self, i):
        j = self.t.find("\n", i)
        if j < 0:
            return self.n
        if j > i and self.t[j - 1] == "\r":
            return j - 1
        return j

    def block_end(self, i, nested):
        t, n = self.t, self.n
        j = i + 2
        level = 1
        while j < n:
            if t.startswith("*/", j):
                level -= 1
                j += 2
                if level == 0:
                    return j
                continue
            if nested and t.startswith("/*", j):
                level += 1
                j += 2
                continue
            j += 1
        return n

    def js(self, i, stop):
        t, n = self.t, self.n
        depth = 0
        prev = "start"
        while i < n:
            c = t[i]
            if c in WS:
                i += 1
                continue
            if c == "/" and i + 1 < n and t[i + 1] == "/":
                e = self.line_end(i)
                self.comment(i, e, "line")
                i = e
                continue
            if c == "/" and i + 1 < n and t[i + 1] == "*":
                e = t.find("*/", i + 2)
                e = n if e < 0 else e + 2
                self.comment(i, e, "block")
                i = e
                continue
            if c == "#" and i == 0 and t.startswith("#!"):
                e = self.line_end(i)
                self.comment(i, e, "hashbang")
                i = e
                continue
            if c == "/":
                if prev in ("start", "op", "kw"):
                    e = self.js_regex(i)
                    if e is not None:
                        self.literal(i, e)
                        i = e
                        prev = "value"
                        continue
                i += 1
                prev = "op"
                continue
            if c == "'" or c == '"':
                e = self.js_string(i)
                self.literal(i, e)
                i = e
                prev = "value"
                continue
            if c == "`":
                i = self.js_template(i)
                prev = "value"
                continue
            if c == "<" and self.jsx and prev in ("start", "op", "kw") and i + 1 < n and (t[i + 1] == ">" or t[i + 1].isalpha() or t[i + 1] in "_$"):
                e = self.jsx_try(i)
                if e is not None:
                    i = e
                    prev = "value"
                    continue
            if c == "{":
                depth += 1
                i += 1
                prev = "op"
                continue
            if c == "}":
                if depth == 0 and stop:
                    return i + 1
                depth = max(0, depth - 1)
                i += 1
                prev = "close"
                continue
            if c in ")]":
                i += 1
                prev = "close"
                continue
            if ident_char(c) or c == "#" or (c == "." and i + 1 < n and t[i + 1].isdigit()):
                number = c.isdigit() or c == "."
                j = i + 1
                while j < n and (ident_char(t[j]) or (number and t[j] == ".")):
                    j += 1
                prev = "kw" if t[i:j] in REGEX_KEYWORDS else "value"
                i = j
                continue
            if c in "+-" and i + 1 < n and t[i + 1] == c:
                i += 2
                prev = "close" if prev in ("value", "close") else "op"
                continue
            if c == "!" and self.ts and prev in ("value", "close") and i > 0 and t[i - 1] not in WS and not (i + 1 < n and t[i + 1] == "="):
                i += 1
                prev = "close"
                continue
            i += 1
            prev = "op"
        return -1 if stop else n

    def js_regex(self, i):
        t, n = self.t, self.n
        j = i + 1
        in_class = False
        while j < n:
            c = t[j]
            if c == "\r" or c == "\n":
                return None
            if c == "\\":
                j += 2
                continue
            if in_class:
                if c == "]":
                    in_class = False
            elif c == "[":
                in_class = True
            elif c == "/":
                j += 1
                while j < n and ident_char(t[j]):
                    j += 1
                return j
            j += 1
        return None

    def js_string(self, i):
        t, n = self.t, self.n
        q = t[i]
        j = i + 1
        while j < n:
            c = t[j]
            if c == "\\":
                j += 3 if t.startswith("\r\n", j + 1) else 2
                continue
            if c == q:
                return j + 1
            if c == "\n" or c == "\r":
                return j
            j += 1
        return n

    def js_template(self, i):
        t, n = self.t, self.n
        j = i + 1
        seg = i
        while j < n:
            c = t[j]
            if c == "\\":
                j += 2
                continue
            if c == "`":
                self.literal(seg, j + 1)
                return j + 1
            if c == "$" and j + 1 < n and t[j + 1] == "{":
                self.literal(seg, j + 2)
                j = self.js(j + 2, True)
                if j < 0:
                    return n
                seg = j - 1
                continue
            j += 1
        self.literal(seg, n)
        return n

    def jsx_try(self, i):
        mark_c = len(self.out.comments)
        mark_l = len(self.out.literals)
        e = self.jsx_element(i)
        if e is None:
            del self.out.comments[mark_c:]
            del self.out.literals[mark_l:]
        return e

    def jsx_skip(self, j):
        t, n = self.t, self.n
        while j < n:
            c = t[j]
            if c in WS:
                j += 1
                continue
            if t.startswith("//", j):
                e = self.line_end(j)
                self.comment(j, e, "line")
                j = e
                continue
            if t.startswith("/*", j):
                e = t.find("*/", j + 2)
                e = n if e < 0 else e + 2
                self.comment(j, e, "block")
                j = e
                continue
            break
        return j

    def jsx_name(self, j):
        t, n = self.t, self.n
        k = j
        while k < n and (ident_char(t[k]) or t[k] in ".-:"):
            k += 1
        return k

    def jsx_element(self, i):
        t, n = self.t, self.n
        j = i + 1
        if j < n and t[j] == ">":
            name = ""
            j += 1
        else:
            if j >= n or not (t[j].isalpha() or t[j] in "_$"):
                return None
            k = self.jsx_name(j)
            name = t[j:k]
            j = k
            while True:
                j = self.jsx_skip(j)
                if j >= n:
                    return None
                c = t[j]
                if c == "/":
                    if j + 1 < n and t[j + 1] == ">":
                        return j + 2
                    return None
                if c == ">":
                    j += 1
                    break
                if c == "{":
                    j = self.js(j + 1, True)
                    if j < 0:
                        return None
                    continue
                if c.isalpha() or c in "_$":
                    j = self.jsx_skip(self.jsx_name(j))
                    if j < n and t[j] == "=":
                        j = self.jsx_skip(j + 1)
                        if j >= n:
                            return None
                        q = t[j]
                        if q in "\"'":
                            e = t.find(q, j + 1)
                            if e < 0:
                                return None
                            self.literal(j, e + 1)
                            j = e + 1
                        elif q == "{":
                            j = self.js(j + 1, True)
                            if j < 0:
                                return None
                        elif q == "<":
                            e = self.jsx_element(j)
                            if e is None:
                                return None
                            j = e
                        else:
                            return None
                    continue
                return None
        while j < n:
            c = t[j]
            if c == "{":
                mark = len(self.out.comments)
                e = self.js(j + 1, True)
                if e < 0:
                    return None
                self.jsx_container(j, e, mark)
                j = e
                continue
            if c == "<":
                if j + 1 < n and t[j + 1] == "/":
                    k = j + 2
                    while k < n and t[k] in WS:
                        k += 1
                    m = self.jsx_name(k)
                    close = t[k:m]
                    while m < n and t[m] in WS:
                        m += 1
                    if m < n and t[m] == ">" and close == name:
                        return m + 1
                    return None
                e = self.jsx_element(j)
                if e is None:
                    return None
                j = e
                continue
            j += 1
        return None

    def jsx_container(self, s, e, mark):
        new = self.out.comments[mark:]
        if not new or any(c.keep for c in new):
            return
        pos = s + 1
        rest = []
        for c in new:
            rest.append(self.t[pos:c.start])
            pos = c.end
        rest.append(self.t[pos:e - 1])
        if "".join(rest).strip() == "":
            del self.out.comments[mark:]
            self.out.comments.append(Comment(s, e, kind="jsx"))

    def kt(self, i, stop):
        t, n = self.t, self.n
        depth = 0
        nested = self.lang == "kotlin"
        while i < n:
            c = t[i]
            if c == "/" and i + 1 < n and t[i + 1] == "/":
                e = self.line_end(i)
                self.comment(i, e, "line")
                i = e
                continue
            if c == "/" and i + 1 < n and t[i + 1] == "*":
                e = self.block_end(i, nested)
                self.comment(i, e, "block")
                i = e
                continue
            if c == "#" and i == 0 and t.startswith("#!"):
                e = self.line_end(i)
                self.comment(i, e, "hashbang")
                i = e
                continue
            if c == '"':
                i = self.kt_raw(i) if t.startswith('"""', i) else self.kt_string(i)
                continue
            if c == "'":
                e = self.kt_char(i)
                self.literal(i, e)
                i = e
                continue
            if c == "`":
                e = t.find("`", i + 1)
                e = n if e < 0 else e + 1
                self.literal(i, e)
                i = e
                continue
            if c == "{":
                depth += 1
            elif c == "}":
                if depth == 0 and stop:
                    return i + 1
                depth = max(0, depth - 1)
            i += 1
        return -1 if stop else n

    def kt_string(self, i):
        t, n = self.t, self.n
        j = i + 1
        seg = i
        while j < n:
            c = t[j]
            if c == "\\":
                j += 2
                continue
            if c == '"':
                self.literal(seg, j + 1)
                return j + 1
            if c == "\n":
                break
            if c == "$" and self.lang == "kotlin" and j + 1 < n and t[j + 1] == "{":
                self.literal(seg, j + 2)
                j = self.kt(j + 2, True)
                if j < 0:
                    return n
                seg = j - 1
                continue
            j += 1
        self.literal(seg, j)
        return j

    def kt_raw(self, i):
        t, n = self.t, self.n
        java = self.lang == "java"
        j = i + 3
        seg = i
        while j < n:
            c = t[j]
            if java and c == "\\":
                j += 2
                continue
            if t.startswith('"""', j):
                k = j + 3
                if not java:
                    while k < n and t[k] == '"':
                        k += 1
                self.literal(seg, k)
                return k
            if not java and c == "$" and j + 1 < n and t[j + 1] == "{":
                self.literal(seg, j + 2)
                j = self.kt(j + 2, True)
                if j < 0:
                    return n
                seg = j - 1
                continue
            j += 1
        self.literal(seg, n)
        return n

    def kt_char(self, i):
        t, n = self.t, self.n
        j = i + 1
        while j < n and t[j] != "\n":
            if t[j] == "\\":
                j += 2
                continue
            if t[j] == "'":
                return j + 1
            j += 1
        return j

    def css(self):
        t, n = self.t, self.n
        i = 0
        while i < n:
            c = t[i]
            if c == "/" and t.startswith("/*", i):
                e = t.find("*/", i + 2)
                e = n if e < 0 else e + 2
                self.comment(i, e, "block")
                i = e
                continue
            if c == "'" or c == '"':
                j = i + 1
                while j < n:
                    if t[j] == "\\":
                        j += 2
                        continue
                    if t[j] == c:
                        j += 1
                        break
                    if t[j] == "\n":
                        break
                    j += 1
                j = min(j, n)
                self.literal(i, j)
                i = j
                continue
            if c in "uU" and t[i:i + 4].lower() == "url(" and (i == 0 or not (t[i - 1].isalnum() or t[i - 1] in "-_")):
                j = i + 4
                while j < n and t[j] in WS:
                    j += 1
                if j < n and t[j] not in "'\"":
                    e = t.find(")", j)
                    e = n if e < 0 else e + 1
                    self.literal(i, e)
                    i = e
                    continue
                i = j
                continue
            i += 1

    def sql(self):
        t, n = self.t, self.n
        i = 0
        while i < n:
            c = t[i]
            if c == "-" and t.startswith("--", i):
                e = self.line_end(i)
                self.comment(i, e, "line")
                i = e
                continue
            if c == "/" and t.startswith("/*", i):
                e = self.block_end(i, True)
                self.comment(i, e, "block")
                i = e
                continue
            if c == "'" or c == '"':
                escapes = c == "'" and i > 0 and t[i - 1] in "eE" and (i < 2 or not ident_char(t[i - 2]))
                j = i + 1
                while j < n:
                    if escapes and t[j] == "\\":
                        j += 2
                        continue
                    if t[j] == c:
                        if j + 1 < n and t[j + 1] == c:
                            j += 2
                            continue
                        j += 1
                        break
                    j += 1
                j = min(j, n)
                self.literal(i, j)
                i = j
                continue
            if c == "$" and (i == 0 or not ident_char(t[i - 1])):
                m = SQL_DOLLAR.match(t, i)
                if m:
                    tag = m.group(0)
                    e = t.find(tag, m.end())
                    e = n if e < 0 else e + len(tag)
                    self.literal(i, e)
                    i = e
                    continue
            i += 1

    def after_continuation(self, i):
        t = self.t
        ls = t.rfind("\n", 0, i) + 1
        if ls == 0:
            return False
        pe = ls - 1
        if pe > 0 and t[pe - 1] == "\r":
            pe -= 1
        ps = t.rfind("\n", 0, max(0, ls - 1)) + 1
        prev = t[ps:pe]
        stripped = prev.rstrip("\\")
        if (len(prev) - len(stripped)) % 2 == 0:
            return False
        for c in reversed(self.out.comments):
            if c.end == pe:
                return False
            if c.end < ps:
                break
        return True

    def sh(self, i, stop):
        t, n = self.t, self.n
        word = True
        paren = 0
        pending = []
        while i < n:
            c = t[i]
            if c == "\n":
                i += 1
                if pending:
                    i = self.sh_heredocs(i, pending)
                    pending = []
                word = True
                continue
            if c in " \t\r":
                i += 1
                word = True
                continue
            if c == "\\":
                if t.startswith("\\\n", i):
                    i += 2
                    continue
                if t.startswith("\\\r\n", i):
                    i += 3
                    continue
                i += 2
                word = False
                continue
            if c == "#" and word:
                e = self.line_end(i)
                cm = self.comment(i, e, "line")
                if self.after_continuation(i):
                    cm.keep_line = True
                i = e
                continue
            if c == "'":
                e = t.find("'", i + 1)
                e = n if e < 0 else e + 1
                self.literal(i, e)
                i = e
                word = False
                continue
            if c == "$" and i + 1 < n:
                d = t[i + 1]
                if d == "'":
                    e = self.sh_ansi(i + 1)
                    self.literal(i, e)
                    i = e
                    word = False
                    continue
                if d == '"':
                    i += 1
                    word = False
                    continue
                if d == "(":
                    if t.startswith("$((", i):
                        i = self.sh_arith(i + 3)
                    else:
                        j = self.sh(i + 2, ")")
                        i = n if j < 0 else j
                    word = False
                    continue
                if d == "{":
                    e = self.sh_brace(i + 2)
                    self.literal(i, e)
                    i = e
                    word = False
                    continue
                i += 2 if d in "#?$!@*-0123456789" else 1
                word = False
                continue
            if c == '"':
                i = self.sh_dquote(i)
                word = False
                continue
            if c == "`":
                if stop == "`":
                    return i + 1
                j = self.sh(i + 1, "`")
                i = n if j < 0 else j
                word = False
                continue
            if c == "(":
                paren += 1
                i += 1
                word = True
                continue
            if c == ")":
                if stop == ")" and paren == 0:
                    return i + 1
                paren = max(0, paren - 1)
                i += 1
                word = True
                continue
            if c == "<" and t.startswith("<<<", i):
                i += 3
                word = True
                continue
            if c == "<" and t.startswith("<<", i):
                j = i + 2
                strip = j < n and t[j] == "-"
                if strip:
                    j += 1
                while j < n and t[j] in " \t":
                    j += 1
                k = j
                while k < n and t[k] not in " \t\r\n;&|<>()":
                    if t[k] in "'\"":
                        m = t.find(t[k], k + 1)
                        k = n if m < 0 else m + 1
                        continue
                    k += 1
                delim = t[j:k].replace("'", "").replace('"', "").replace("\\", "")
                if delim:
                    pending.append((delim, strip))
                i = k
                word = False
                continue
            if c in ";&|<>":
                i += 1
                word = True
                continue
            i += 1
            word = False
        return -1 if stop else n

    def sh_heredocs(self, i, pending):
        t, n = self.t, self.n
        for delim, strip in pending:
            start = i
            found = False
            while i < n:
                e = t.find("\n", i)
                le = n if e < 0 else e
                line = t[i:le].rstrip("\r")
                nxt = n if e < 0 else e + 1
                if (line.lstrip("\t") if strip else line) == delim:
                    self.literal(start, i)
                    i = nxt
                    found = True
                    break
                i = nxt
            if not found:
                self.literal(start, n)
        return i

    def sh_ansi(self, j):
        t, n = self.t, self.n
        k = j + 1
        while k < n:
            if t[k] == "\\":
                k += 2
                continue
            if t[k] == "'":
                return k + 1
            k += 1
        return n

    def sh_arith(self, j):
        t, n = self.t, self.n
        depth = 2
        while j < n:
            if t[j] == "(":
                depth += 1
            elif t[j] == ")":
                depth -= 1
                if depth == 0:
                    return j + 1
            j += 1
        return n

    def sh_brace(self, j):
        t, n = self.t, self.n
        depth = 1
        while j < n:
            c = t[j]
            if c == "\\":
                j += 2
                continue
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    return j + 1
            j += 1
        return n

    def sh_dquote(self, i):
        t, n = self.t, self.n
        j = i + 1
        seg = i
        while j < n:
            c = t[j]
            if c == "\\":
                j += 2
                continue
            if c == '"':
                self.literal(seg, j + 1)
                return j + 1
            if c == "$" and j + 1 < n and t[j + 1] == "(":
                if t.startswith("$((", j):
                    j = self.sh_arith(j + 3)
                    continue
                self.literal(seg, j + 2)
                k = self.sh(j + 2, ")")
                if k < 0:
                    return n
                j = k
                seg = k - 1
                continue
            if c == "$" and j + 1 < n and t[j + 1] == "{":
                j = self.sh_brace(j + 2)
                continue
            if c == "`":
                self.literal(seg, j + 1)
                k = self.sh(j + 1, "`")
                if k < 0:
                    return n
                j = k
                seg = k - 1
                continue
            j += 1
        self.literal(seg, n)
        return n

    def heredoc_markers(self, line):
        out = []
        i = 0
        n = len(line)
        quote = None
        while i < n:
            c = line[i]
            if quote:
                if c == "\\" and quote == '"':
                    i += 2
                    continue
                if c == quote:
                    quote = None
                i += 1
                continue
            if c in "'\"":
                quote = c
                i += 1
                continue
            if line.startswith("<<", i) and not line.startswith("<<<", i):
                j = i + 2
                strip = j < n and line[j] == "-"
                if strip:
                    j += 1
                k = j
                while k < n and line[k] not in " \t;&|<>()":
                    k += 1
                delim = line[j:k].replace("'", "").replace('"', "").replace("\\", "")
                if delim and (delim[0].isalpha() or delim[0] == "_"):
                    out.append((delim, strip))
                i = k
                continue
            i += 1
        return out

    def dockerfile(self):
        t = self.t
        rows = line_table(t)
        idx = 0
        pending = []
        while idx < len(rows):
            ls, ce, _ = rows[idx]
            if pending:
                for delim, strip in pending:
                    start = rows[idx][0] if idx < len(rows) else self.n
                    found = False
                    while idx < len(rows):
                        a, b, _ = rows[idx]
                        line = t[a:b]
                        idx += 1
                        if (line.lstrip("\t") if strip else line) == delim:
                            self.literal(start, a)
                            found = True
                            break
                    if not found:
                        self.literal(start, self.n)
                pending = []
                continue
            line = t[ls:ce]
            body = line.lstrip(" \t")
            if body.startswith("#"):
                self.comment(ce - len(body), ce, "line")
                idx += 1
                continue
            pending = self.heredoc_markers(line)
            idx += 1

    def properties(self):
        t = self.t
        cont = False
        for ls, ce, _ in line_table(t):
            line = t[ls:ce]
            if cont:
                cont = (len(line) - len(line.rstrip("\\"))) % 2 == 1
                continue
            body = line.lstrip(" \t\f")
            if body[:1] in ("#", "!"):
                self.comment(ce - len(body), ce, "line")
                continue
            cont = (len(line) - len(line.rstrip("\\"))) % 2 == 1

    def dotenv(self):
        t, n = self.t, self.n
        i = 0
        while i < n:
            ce = self.line_end(i)
            nl = t.find("\n", i)
            nxt = n if nl < 0 else nl + 1
            line = t[i:ce]
            body = line.lstrip(" \t")
            if body.startswith("#"):
                self.comment(ce - len(body), ce, "line")
                i = nxt
                continue
            eq = line.find("=")
            if eq < 0:
                i = nxt
                continue
            j = i + eq + 1
            while j < ce and t[j] in " \t":
                j += 1
            if j < ce and t[j] in "\"'":
                q = t[j]
                k = j + 1
                while k < n:
                    if q == '"' and t[k] == "\\":
                        k += 2
                        continue
                    if t[k] == q:
                        break
                    k += 1
                k = min(k + 1, n)
                self.literal(j, k)
                ce = self.line_end(k) if k < n else n
                nl = t.find("\n", k) if k < n else -1
                nxt = n if nl < 0 else nl + 1
                j = k
            while j < ce:
                if t[j] == "#" and t[j - 1] in " \t":
                    self.comment(j, ce, "line")
                    break
                j += 1
            i = nxt

    def toml(self):
        t, n = self.t, self.n
        i = 0
        while i < n:
            c = t[i]
            if c == "#":
                e = self.line_end(i)
                self.comment(i, e, "line")
                i = e
                continue
            if c == '"' or c == "'":
                if t.startswith(c * 3, i):
                    j = i + 3
                    end = n
                    while j < n:
                        if c == '"' and t[j] == "\\":
                            j += 2
                            continue
                        if t.startswith(c * 3, j):
                            k = j + 3
                            while k < n and k < j + 5 and t[k] == c:
                                k += 1
                            end = k
                            break
                        j += 1
                    self.literal(i, end)
                    i = end
                    continue
                j = i + 1
                end = None
                while j < n and t[j] != "\n":
                    if c == '"' and t[j] == "\\":
                        j += 2
                        continue
                    if t[j] == c:
                        end = j + 1
                        break
                    j += 1
                end = min(j, n) if end is None else end
                self.literal(i, end)
                i = end
                continue
            i += 1

    def xml(self):
        t, n = self.t, self.n
        i = 0
        while i < n:
            j = t.find("<", i)
            if j < 0:
                break
            if t.startswith("<!--", j):
                e = t.find("-->", j + 4)
                e = n if e < 0 else e + 3
                self.comment(j, e, "block")
                i = e
                continue
            if t.startswith("<![CDATA[", j):
                e = t.find("]]>", j)
                e = n if e < 0 else e + 3
                self.literal(j, e)
                i = e
                continue
            if t.startswith("<?", j):
                e = t.find("?>", j)
                e = n if e < 0 else e + 2
                self.literal(j, e)
                i = e
                continue
            k = j + 1
            depth = 0
            while k < n:
                ch = t[k]
                if ch in "'\"":
                    m = t.find(ch, k + 1)
                    m = n if m < 0 else m + 1
                    self.literal(k, m)
                    k = m
                    continue
                if ch == "[":
                    depth += 1
                elif ch == "]":
                    depth -= 1
                elif ch == ">" and depth <= 0:
                    k += 1
                    break
                k += 1
            i = k

    def yaml(self):
        t = self.t
        rows = line_table(t)
        rel = "/" + self.path.replace("\\", "/")
        workflow = "/.github/workflows/" in rel or rel.rsplit("/", 1)[-1] in ("action.yml", "action.yaml")
        recs = []
        blocks = []
        in_q = None
        q_start = 0
        flow = 0
        block = None
        idx = 0
        while idx < len(rows):
            ls, ce, _ = rows[idx]
            if block is not None:
                line = t[ls:ce]
                ind = len(line) - len(line.lstrip(" "))
                if line.strip(" \t") == "":
                    idx += 1
                    continue
                if block["indent"] is None and ind > block["threshold"]:
                    block["indent"] = ind
                if block["indent"] is not None and ind >= block["indent"]:
                    block["last"] = idx
                    idx += 1
                    continue
                blocks.append(block)
                block = None
            pos = ls
            if in_q is None and flow == 0:
                while pos < ce and t[pos] in " \t":
                    pos += 1
                if pos < ce and t[pos] == "#":
                    self.comment(pos, ce, "line")
                    idx += 1
                    continue
            indent_col = pos - ls
            plain = False
            node_start = pos
            node_col = indent_col
            key = None
            key_col = None
            dash_col = None
            last_ind = None
            rec = None
            while pos < ce:
                c = t[pos]
                if in_q is not None:
                    j = pos
                    closed = False
                    while j < ce:
                        if in_q == '"' and t[j] == "\\":
                            j += 2
                            continue
                        if t[j] == in_q:
                            if in_q == "'" and j + 1 < ce and t[j + 1] == "'":
                                j += 2
                                continue
                            closed = True
                            break
                        j += 1
                    if closed:
                        self.literal(q_start, j + 1)
                        in_q = None
                        pos = j + 1
                        continue
                    pos = ce
                    break
                if c in " \t":
                    pos += 1
                    continue
                if c == "#" and (pos == ls or t[pos - 1] in " \t"):
                    keep = None
                    if key == "uses" and SHA_PIN.search(t, ls, pos):
                        keep = True
                    self.comment(pos, ce, "line", keep=keep)
                    if rec is not None:
                        rec["comment"] = pos
                    pos = ce
                    break
                if plain:
                    if c == ":" and (pos + 1 >= ce or t[pos + 1] in " \t" or (flow and t[pos + 1] in ",[]{}")):
                        key = t[node_start:pos].strip()
                        key_col = node_col
                        last_ind = ":"
                        plain = False
                        if rec is None and flow == 0:
                            rec = {"row": idx, "indent": indent_col, "key_col": key_col, "key": key, "colon": pos, "end": ce,
                                   "dash": dash_col is not None and dash_col < key_col, "comment": None}
                            recs.append(rec)
                        pos += 1
                        continue
                    if not (flow and c in ",[]{}"):
                        pos += 1
                        continue
                    plain = False
                if c == '"' or c == "'":
                    in_q = c
                    q_start = pos
                    node_start = pos
                    node_col = pos - ls
                    pos += 1
                    continue
                if c in "[{":
                    flow += 1
                    pos += 1
                    continue
                if c in "]}":
                    flow = max(0, flow - 1)
                    pos += 1
                    continue
                if c == ",":
                    pos += 1
                    continue
                if c in "-?:" and (pos + 1 >= ce or t[pos + 1] in " \t"):
                    if c == ":":
                        key = t[node_start:pos].strip().strip("'\"")
                        key_col = node_col
                        last_ind = ":"
                        if rec is None and flow == 0:
                            rec = {"row": idx, "indent": indent_col, "key_col": key_col, "key": key, "colon": pos, "end": ce,
                                   "dash": dash_col is not None and dash_col < key_col, "comment": None}
                            recs.append(rec)
                    else:
                        dash_col = pos - ls
                        last_ind = c
                    pos += 1
                    continue
                if c in "|>" and flow == 0:
                    j = pos + 1
                    explicit = None
                    while j < ce and t[j] in "+-0123456789":
                        if t[j].isdigit():
                            explicit = int(t[j])
                        j += 1
                    if last_ind == ":":
                        threshold = key_col
                    elif last_ind in ("-", "?"):
                        threshold = dash_col
                    else:
                        threshold = -1
                    block = {
                        "threshold": threshold,
                        "indent": max(threshold, 0) + explicit if explicit else None,
                        "kind": c,
                        "header": idx,
                        "rec": rec if last_ind == ":" else None,
                        "key": key if last_ind == ":" else None,
                    }
                    pos = j
                    continue
                if c in "&*!":
                    j = pos + 1
                    while j < ce and t[j] not in " \t":
                        j += 1
                    pos = j
                    continue
                plain = True
                node_start = pos
                node_col = pos - ls
                pos += 1
            idx += 1
        if block is not None:
            blocks.append(block)
        default_other = self.yaml_default_other(recs)
        for b in blocks:
            self.yaml_block(b, rows, recs, workflow, default_other)

    def yaml_value(self, rec):
        end = rec["comment"] if rec["comment"] is not None else rec["end"]
        return self.t[rec["colon"] + 1:end].strip().strip("'\"")

    def yaml_parent(self, recs, k):
        col = recs[k]["key_col"]
        j = k - 1
        while j >= 0:
            if recs[j]["key_col"] < col:
                return j
            j -= 1
        return None

    def yaml_default_other(self, recs):
        for k, r in enumerate(recs):
            if r["key"] in ("runs-on", "os") and "windows" in self.yaml_value(r).lower():
                return True
            if r["key"] == "shell" and not is_posix_shell(self.yaml_value(r)):
                p = self.yaml_parent(recs, k)
                if p is not None and recs[p]["key"] == "run":
                    g = self.yaml_parent(recs, p)
                    if g is not None and recs[g]["key"] == "defaults":
                        return True
        return False

    def yaml_step_shell(self, rec, recs, default_other):
        i = next(k for k, r in enumerate(recs) if r is rec)
        col = rec["key_col"]
        k = i
        while k >= 0:
            r = recs[k]
            if r["key_col"] == col:
                if r["key"] == "shell":
                    return is_posix_shell(self.yaml_value(r))
                if r["dash"]:
                    break
            elif r["key_col"] < col:
                break
            k -= 1
        k = i + 1
        while k < len(recs):
            r = recs[k]
            if r["key_col"] < col or (r["dash"] and r["key_col"] <= col):
                break
            if r["key_col"] == col and r["key"] == "shell":
                return is_posix_shell(self.yaml_value(r))
            k += 1
        return not default_other

    def yaml_block(self, b, rows, recs, workflow, default_other):
        last = b.get("last")
        if last is None:
            return
        first = b["header"] + 1
        shell = (
            workflow
            and b["kind"] == "|"
            and b["key"] == "run"
            and b["rec"] is not None
            and self.yaml_step_shell(b["rec"], recs, default_other)
        )
        if not shell:
            self.literal(rows[first][0], rows[last][1])
            return
        ind = b["indent"]
        parts = []
        mapping = []
        for r in range(first, last + 1):
            ls, ce, _ = rows[r]
            line = self.t[ls:ce]
            cut = 0
            while cut < ind and cut < len(line) and line[cut] == " ":
                cut += 1
            seg = line[cut:]
            mapping.extend(range(ls + cut, ce))
            mapping.append(ce)
            parts.append(seg)
            parts.append("\n")
        mapping.append(rows[last][1])
        sub = "".join(parts)
        inner = Scan(sub, "shell", self.path)
        inner.sh(0, None)
        for cm in inner.out.comments:
            cm.start = mapping[cm.start]
            cm.end = mapping[min(cm.end, len(sub))]
            self.out.comments.append(cm)
        for s, e in inner.out.literals:
            self.literal(mapping[s], mapping[min(e, len(sub))])


def is_posix_shell(value):
    words = value.split()
    return bool(words) and words[0] in ("bash", "sh")


def lex(text, lang, path=""):
    sc = Scan(text, lang, path)
    if lang in JS_LANGS:
        sc.js(0, False)
    elif lang in ("kotlin", "java"):
        sc.kt(0, False)
    elif lang == "css":
        sc.css()
    elif lang == "sql":
        sc.sql()
    elif lang == "shell":
        sc.sh(0, None)
    elif lang == "yaml":
        sc.yaml()
    elif lang == "toml":
        sc.toml()
    elif lang == "properties":
        sc.properties()
    elif lang == "dotenv":
        sc.dotenv()
    elif lang == "dockerfile":
        sc.dockerfile()
    elif lang == "xml":
        sc.xml()
    else:
        raise StripError(f"no lexer for {lang}")
    sc.out.comments.sort(key=lambda c: (c.start, c.end))
    sc.out.literals.sort()
    return sc.out


def python_tokens(text):
    try:
        return list(tokenize.generate_tokens(io.StringIO(text).readline))
    except (tokenize.TokenError, SyntaxError, IndentationError) as exc:
        raise StripError(f"python tokenize failed: {exc}") from exc


def python_tree(text):
    try:
        return ast.parse(text)
    except SyntaxError as exc:
        raise StripError(f"python parse failed: {exc}") from exc


def reads_doc(tokens):
    return any(tk.type == tokenize.NAME and tk.string == "__doc__" for tk in tokens)


def docstrings(tree):
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
                yield node, body[0]


def python_edits(text):
    rows = line_table(text)
    tokens = python_tokens(text)

    def char_off(row, col):
        return rows[row - 1][0] + col

    def byte_off(row, col):
        ls, _, fe = rows[row - 1]
        return ls + len(text[ls:fe].encode("utf-8")[:col].decode("utf-8", "replace"))

    edits = []
    for tk in tokens:
        if tk.type != tokenize.COMMENT:
            continue
        row, col = tk.start
        body = tk.string
        s = char_off(row, col)
        e = s + len(body)
        if row == 1 and col == 0 and body.startswith("#!"):
            continue
        if row <= 2 and CODING.match(text[rows[row - 1][0]:rows[row - 1][1]]):
            continue
        if LICENSE.search(body):
            continue
        m = PY_DIRECTIVE.search(body)
        if m:
            if m.start() == 0:
                continue
            edits.append(Comment(s, e, replacement=body[m.start():], kind="comment"))
            continue
        edits.append(Comment(s, e, kind="comment"))
    if reads_doc(tokens):
        return edits
    tree = python_tree(text)
    n = len(text)
    for node, first in docstrings(tree):
        s = byte_off(first.lineno, first.col_offset)
        e = byte_off(first.end_lineno, first.end_col_offset)
        k = e
        while k < n and text[k] in " \t":
            k += 1
        if k < n and text[k] == ";":
            e = k + 1
            while e < n and text[e] in " \t":
                e += 1
        only = len(node.body) == 1 and not isinstance(node, ast.Module)
        edits.append(Comment(s, e, replacement="pass" if only else "", kind="docstring", eat_blank_after=not only))
    edits.sort(key=lambda c: (c.start, c.end))
    return edits


def python_reference(text):
    tree = python_tree(text)
    if not reads_doc(python_tokens(text)):
        for node, _ in list(docstrings(tree)):
            rest = node.body[1:]
            node.body = rest if rest or isinstance(node, ast.Module) else [ast.Pass()]
    return ast.dump(tree)


def find_edits(text, lang, path=""):
    if lang == "python":
        return python_edits(text)
    return [c for c in lex(text, lang, path).comments if not c.keep]


def rebuild_line(text, ls, ce, local, join):
    pieces = []
    pos = ls
    for c in local:
        s = max(c.start, ls)
        e = min(c.end, ce)
        if s > pos:
            pieces.append(text[pos:s])
        before = "".join(pieces)
        rep = c.replacement if c.start >= ls else ""
        if rep:
            pieces.append(rep)
            pos = e
            continue
        after = text[e:ce]
        if before.strip(LINE_WS) == "" or before[-1:] in LINE_WS:
            pos = e
            while pos < ce and text[pos] in LINE_WS:
                pos += 1
            continue
        if join and after[:1] and after[:1] not in LINE_WS:
            pieces.append(" ")
        pos = max(pos, e)
    tail = text[pos:ce]
    content = "".join(pieces)
    if tail.strip(LINE_WS) == "":
        content = content.rstrip(LINE_WS)
    else:
        content += tail
    return content


def apply_edits(text, edits, lang=""):
    edits = sorted(edits, key=lambda c: (c.start, c.end))
    for a, b in zip(edits, edits[1:]):
        if b.start < a.end:
            raise StripError(f"overlapping comment spans at offset {b.start}")
    rows = line_table(text)
    join = lang != "xml"
    out = []
    k = 0
    for ls, ce, fe in rows:
        while k < len(edits) and edits[k].end <= ls:
            k += 1
        local = []
        m = k
        while m < len(edits) and edits[m].start < fe:
            if edits[m].end > ls and edits[m].start < max(ce, ls + 1):
                local.append(edits[m])
            m += 1
        if not local:
            out.append({"content": text[ls:ce], "term": text[ce:fe], "state": "plain", "eat": False})
            continue
        content = rebuild_line(text, ls, ce, local, join)
        dropped = content.strip(LINE_WS) == "" and not any(c.keep_line for c in local)
        out.append({
            "content": content if content.strip(LINE_WS) else "",
            "term": text[ce:fe],
            "state": "dropped" if dropped else "edited",
            "eat": any(c.eat_blank_after for c in local),
        })

    def blank(r):
        return out[r]["state"] == "plain" and out[r]["content"].strip(LINE_WS) == ""

    drop = [r["state"] == "dropped" for r in out]
    total = len(out)
    i = 0
    while i < total:
        if out[i]["state"] != "dropped":
            i += 1
            continue
        j = i
        eat = False
        while j < total and out[j]["state"] == "dropped":
            eat = eat or out[j]["eat"]
            j += 1
        p = i - 1
        if eat or p < 0:
            r = j
            while r < total and blank(r):
                drop[r] = True
                r += 1
        elif j < total and blank(p) and blank(j):
            drop[j] = True
        if j >= total and lang != "yaml":
            r = p
            while r >= 0 and blank(r) and not drop[r]:
                drop[r] = True
                r -= 1
        i = j
    return "".join(r["content"] + r["term"] for r, d in zip(out, drop) if not d)


def significant(text, lexed, lang=""):
    glue = "" if lang == "xml" else " "
    spans = [(c.start, c.end, "K" if c.keep else None) for c in lexed.comments]
    spans += [(s, e, "L") for s, e in lexed.literals]
    spans.sort(key=lambda x: (x[0], x[1]))
    out = []
    buf = []
    pos = 0
    for s, e, kind in spans:
        if s < pos:
            continue
        buf.append(text[pos:s])
        if kind is None:
            buf.append(glue)
        else:
            out.extend("".join(buf).split())
            buf = []
            out.append(kind + text[s:e])
        pos = e
    buf.append(text[pos:])
    out.extend("".join(buf).split())
    return out


def shell_signature(value):
    return significant(value, lex(value, "shell"))


def normalise_yaml(value, workflow):
    if isinstance(value, dict):
        return {k: (shell_signature(v) if workflow and k == "run" and isinstance(v, str) else normalise_yaml(v, workflow)) for k, v in value.items()}
    if isinstance(value, list):
        return [normalise_yaml(v, workflow) for v in value]
    return value


def parse_properties(text):
    result = []
    logical = ""
    cont = False
    for line in text.splitlines():
        if not cont:
            body = line.lstrip(" \t\f")
            if body[:1] in ("#", "!") or body == "":
                continue
            logical = body
        else:
            logical += line.lstrip(" \t\f")
        cont = (len(line) - len(line.rstrip("\\"))) % 2 == 1
        if cont:
            logical = logical[:-1]
        else:
            result.append(logical)
    return result


def semantic_check(old, new, lang, path):
    if lang == "yaml":
        try:
            import yaml
        except ImportError:
            return
        try:
            before = list(yaml.safe_load_all(old))
        except Exception:
            return
        try:
            after = list(yaml.safe_load_all(new))
        except Exception as exc:
            raise StripError(f"stripped YAML no longer parses: {exc}") from exc
        workflow = "/.github/workflows/" in "/" + path or path.rsplit("/", 1)[-1] in ("action.yml", "action.yaml")
        if normalise_yaml(before, workflow) != normalise_yaml(after, workflow):
            raise StripError("YAML value changed")
    elif lang == "toml":
        import tomllib
        try:
            before = tomllib.loads(old)
        except Exception:
            return
        try:
            after = tomllib.loads(new)
        except Exception as exc:
            raise StripError(f"stripped TOML no longer parses: {exc}") from exc
        if before != after:
            raise StripError("TOML value changed")
    elif lang == "xml":
        import xml.etree.ElementTree as ET
        try:
            before = ET.canonicalize(old, strip_text=True)
        except Exception:
            return
        try:
            after = ET.canonicalize(new, strip_text=True)
        except Exception as exc:
            raise StripError(f"stripped XML no longer parses: {exc}") from exc
        if before != after:
            raise StripError("XML content changed")
    elif lang == "properties":
        if parse_properties(old) != parse_properties(new):
            raise StripError("properties changed")


def verify(old, new, lang, path=""):
    if lang == "python":
        if ast.dump(python_tree(new)) != python_reference(old):
            raise StripError("python AST changed")
        if python_edits(new):
            raise StripError("comments remain after stripping")
        return
    a = lex(old, lang, path)
    b = lex(new, lang, path)
    left = [c for c in b.comments if not c.keep]
    if left:
        raise StripError(f"comment remains after stripping at offset {left[0].start}")
    if significant(old, a, lang) != significant(new, b, lang):
        raise StripError("code outside comments changed")
    semantic_check(old, new, lang, path)


def strip_text(text, lang, path="", check=True):
    bom = "﻿" if text.startswith("﻿") else ""
    body = text[len(bom):]
    edits = find_edits(body, lang, path)
    if not edits:
        return text, []
    new = apply_edits(body, edits, lang)
    if check:
        verify(body, new, lang, path)
        if find_edits(new, lang, path):
            raise StripError("stripping is not idempotent")
    return bom + new, edits


def language_of(rel):
    name = rel.rsplit("/", 1)[-1]
    if name == "Dockerfile" or name.startswith("Dockerfile.") or name.endswith((".Dockerfile", ".dockerfile")):
        return "dockerfile"
    if name.startswith(".env") and name.endswith(".example") or name.endswith(".env.example"):
        return "dotenv"
    dot = name.rfind(".")
    if dot <= 0 and not name.startswith("."):
        return None
    return SUFFIX_LANGUAGE.get(name[dot:].lower()) if dot >= 0 else None


def path_exclusion(rel):
    rel = rel.replace("\\", "/")
    parts = rel.split("/")
    name = parts[-1]
    dirs = parts[:-1]
    lower = name.lower()
    suffix = lower[lower.rfind("."):] if "." in lower else ""
    for a, b in zip(dirs, dirs[1:]):
        if a == "prisma" and b == "migrations":
            return "applied migrations"
        if a == "prisma" and b == "deferred":
            return "deferred migrations"
    if "migrations" in dirs:
        return "migrations"
    for d in dirs:
        if d in EXCLUDED_DIR_NAMES:
            return "generated code" if d == "generated" else "vendored, third-party or build output"
    if dirs[:1] == ["coverage"] or dirs[1:2] == ["coverage"] and dirs[:1] in (["frontend"], ["backend"]):
        return "build output"
    if name in WRAPPER_NAMES or "/gradle/wrapper/" in "/" + rel:
        return "Gradle wrapper"
    if name in GENERATED_NAMES:
        return "generated code"
    if name in LOCK_NAMES or lower.endswith(".lock") or (lower.startswith("requirements") and lower.endswith(".lock")):
        return "lockfile"
    if ".min." in lower:
        return "minified"
    if suffix in (".md", ".mdx", ".markdown"):
        return "documentation"
    if suffix in (".json", ".jsonc", ".json5"):
        return "JSON"
    if suffix == ".snap" or any(d in SNAPSHOT_DIR_NAMES for d in dirs):
        return "test data"
    if any(d in FIXTURE_DIR_NAMES for d in dirs) and suffix not in CODE_SUFFIXES:
        return "test data"
    joined = "/" + "/".join(dirs) + "/"
    if "/src/test/resources/" in joined or "/src/androidTest/resources/" in joined or "/src/main/assets/" in joined:
        return "test data or bundled asset"
    if name.startswith(".env") and language_of(rel) is None:
        return "secrets"
    if language_of(rel) is None:
        return "no lexer for this file type"
    return None


def content_exclusion(text):
    head = text.split("\n", 5)[:5]
    if any(GENERATED.search(line) for line in head):
        return "generated code"
    if any(len(line) > MAX_LINE for line in text.split("\n")):
        return "minified or generated data"
    return None


def tracked_files(root):
    try:
        res = subprocess.run(["git", "-C", str(root), "ls-files", "-z"], capture_output=True, check=False)
    except OSError:
        return None
    if res.returncode != 0:
        return None
    return [p for p in res.stdout.decode("utf-8", "replace").split("\0") if p]


def walked_files(root):
    out = []
    for base, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDED_DIR_NAMES]
        for f in filenames:
            out.append(Path(base, f).relative_to(root).as_posix())
    return out


def candidates(root, paths):
    files = tracked_files(root)
    if files is None:
        files = walked_files(root)
    if not paths:
        return sorted(set(files))
    picked = set()
    for p in paths:
        target = Path(p).resolve()
        try:
            rel = target.relative_to(root).as_posix()
        except ValueError as exc:
            raise SystemExit(f"{p} is outside {root}") from exc
        if target.is_file():
            picked.add(rel)
            continue
        prefix = "" if rel == "." else rel.rstrip("/") + "/"
        picked.update(f for f in files if f.startswith(prefix))
    return sorted(picked)


def in_scope(root, rel):
    reason = path_exclusion(rel)
    if reason:
        return None, None, reason
    path = root / rel
    if not path.is_file():
        return None, None, "missing"
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None, None, "not UTF-8 text"
    reason = content_exclusion(text)
    if reason:
        return None, None, reason
    return language_of(rel), text, None


def position(text, offset):
    body = text[1:] if text.startswith("﻿") else text
    line = body.count("\n", 0, offset) + 1
    col = offset - (body.rfind("\n", 0, offset) + 1) + 1
    return line, col


def excerpt(text, c):
    body = text[1:] if text.startswith("﻿") else text
    s = body[c.start:c.end].strip().splitlines()
    first = s[0] if s else ""
    return first[:80]


def main(argv=None):
    parser = argparse.ArgumentParser(prog="strip_comments.py")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--diff", action="store_true")
    mode.add_argument("--out", metavar="DIR")
    mode.add_argument("--list", action="store_true")
    mode.add_argument("--exclusions", action="store_true")
    parser.add_argument("--root", default=str(ROOT))
    parser.add_argument("--no-verify", action="store_true")
    parser.add_argument("-q", "--quiet", action="store_true")
    parser.add_argument("paths", nargs="*")
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    files = candidates(root, args.paths)
    if args.exclusions:
        for pattern, why in EXCLUSION_RULES:
            print(f"{pattern}  ->  {why}")
        print()
        for rel in files:
            _, _, reason = in_scope(root, rel)
            if reason and reason != "no lexer for this file type":
                print(f"excluded  {rel}  ({reason})")
        return 0
    errors = 0
    findings = 0
    changed = 0
    scanned = 0
    for rel in files:
        lang, text, reason = in_scope(root, rel)
        if reason:
            continue
        scanned += 1
        if args.list:
            print(f"{lang}\t{rel}")
            continue
        try:
            if args.check:
                body = text[1:] if text.startswith("﻿") else text
                edits = find_edits(body, lang, rel)
                for c in edits:
                    line, col = position(text, c.start)
                    print(f"{rel}:{line}:{col}: {c.kind}: {excerpt(text, c)}")
                findings += len(edits)
                continue
            new, edits = strip_text(text, lang, rel, check=not args.no_verify)
        except StripError as exc:
            errors += 1
            print(f"{rel}: error: {exc}", file=sys.stderr)
            continue
        except RecursionError:
            errors += 1
            print(f"{rel}: error: nesting too deep", file=sys.stderr)
            continue
        if new == text:
            continue
        changed += 1
        findings += len(edits)
        if args.write:
            (root / rel).write_bytes(new.encode("utf-8"))
        elif args.out:
            dest = Path(args.out) / rel
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(new.encode("utf-8"))
        elif args.diff:
            sys.stdout.writelines(difflib.unified_diff(text.splitlines(True), new.splitlines(True), f"a/{rel}", f"b/{rel}"))
        elif not args.quiet:
            print(f"{rel}: {len(edits)} comment(s)")
    if args.list:
        return 0
    if args.check:
        print(f"{findings} comment(s) in {scanned} file(s) in scope", file=sys.stderr)
        if errors:
            return 2
        return 1 if findings else 0
    verb = "stripped" if args.write else "would strip"
    print(f"{verb} {findings} comment(s) in {changed} of {scanned} file(s); {errors} error(s)", file=sys.stderr)
    return 2 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
