#!/usr/bin/env python3
"""Generate the shared web questionnaire's vocabularies from ``shared/``, and check for drift.

    python scripts/generate_questionnaire_web.py           # write the outputs
    python scripts/generate_questionnaire_web.py --check   # exit 1 when an output is stale

* ``shared/strings/questionnaire.json`` -> ``frontend/lib/questionnaire/strings.ts``
* ``shared/enums.json`` + ``shared/languages.json`` -> ``frontend/lib/questionnaire/enums.ts``

Both outputs are part of the shared web tree (``shared/questionnaire.sha256``), so they are
byte-identical in both portals: the text below is documentation-portal's ``scripts/generate_shared.py``
web half, header included, and the two generators must agree. Edit ``shared/`` here, run this, then
``python scripts/sync_questionnaire.py --to ../documentation-portal``.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared"
WEB = ROOT / "frontend" / "lib" / "questionnaire"
HEADER = "GENERATED by scripts/generate_shared.py from shared/. Do not edit; edit shared/ and regenerate."
_PLACEHOLDER = re.compile(r"\{([A-Za-z][A-Za-z0-9]*)\}")


def _load(name: str) -> dict:
    return json.loads((SHARED / name).read_text(encoding="utf-8"))


def web_enums(enums: dict, languages: dict) -> str:
    lines = [f"// {HEADER}", ""]
    for name, values in enums["enums"].items():
        literal = ", ".join(json.dumps(v) for v in values)
        lines.append(f"export const {name}Values = [{literal}] as const;")
        lines.append(f"export type {name} = (typeof {name}Values)[number];")
        lines.append("")
    est = ", ".join(json.dumps(v) for v in enums["estimatedCapturedAtSources"])
    lines.append(f"export const EstimatedCapturedAtSources: readonly CapturedAtSource[] = [{est}];")
    lines.append("")
    lines.append("export const Languages: ReadonlyArray<{ code: string; label: string }> = [")
    for lang in languages["languages"]:
        lines.append(f"  {{ code: {json.dumps(lang['code'])}, label: {json.dumps(lang['label'], ensure_ascii=False)} }},")
    lines.append("];")
    lines.append("")
    lines.append("export const LanguageAliases: Readonly<Record<string, string>> = {")
    for alias, code in languages["aliases"].items():
        lines.append(f"  {json.dumps(alias, ensure_ascii=False)}: {json.dumps(code)},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def web_strings(strings: dict) -> str:
    lines = [f"// {HEADER}", ""]
    lines.append("export const questionnaireStrings = {")
    for key, text in strings["strings"].items():
        names = list(dict.fromkeys(_PLACEHOLDER.findall(text)))
        if names:
            params = ", ".join(f"{n}" for n in names)
            typed = "; ".join(f"{n}: string | number" for n in names)
            body = _PLACEHOLDER.sub(lambda m: "${" + m.group(1) + "}", text.replace("\\", "\\\\").replace("`", "\\`"))
            lines.append(f"  {key}: ({{ {params} }}: {{ {typed} }}): string => `{body}`,")
        else:
            lines.append(f"  {key}: {json.dumps(text, ensure_ascii=False)},")
    lines.append("} as const;")
    lines.append("")
    lines.append("export type QuestionnaireStringKey = keyof typeof questionnaireStrings;")
    lines.append("")
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    return {
        WEB / "strings.ts": web_strings(_load("strings/questionnaire.json")),
        WEB / "enums.ts": web_enums(_load("enums.json"), _load("languages.json")),
    }


def main(argv: list[str]) -> int:
    produced = outputs()
    if "--check" in argv:
        stale = [p.relative_to(ROOT).as_posix() for p, text in produced.items()
                 if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
        for rel in stale:
            print(f"stale: {rel}")
        if stale:
            print("Run: python scripts/generate_questionnaire_web.py")
            return 1
        print("shared web vocabularies are current")
        return 0
    for path, text in produced.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(produced)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
