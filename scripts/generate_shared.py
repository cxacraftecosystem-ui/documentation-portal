#!/usr/bin/env python3
"""Generate every runtime's copy of the shared questionnaire vocabularies, and check for drift.

    python scripts/generate_shared.py           # write the outputs
    python scripts/generate_shared.py --check   # exit 1 when any output (or the manifest) is stale

Inputs (``shared/``, written once by feature/q-backend and copied verbatim by the other streams):

* ``enums.json``             -> backend ``app/shared_vocab.py``, web ``lib/shared/enums.ts``,
                                Android ``data/SharedEnums.kt``; and a check that every Prisma enum of
                                the same name in ``backend/prisma/schema.prisma`` has exactly these values
* ``languages.json``         -> the same three files (codes, labels, aliases)
* ``strings/questionnaire.json`` -> web ``lib/strings/questionnaire.ts`` and Android
                                ``res/values/strings_questionnaire.xml``
* every file under ``shared/`` -> ``shared/manifest.json`` (sha256 per file), which each stream's
                                parity test compares its copy against

WHO WRITES WHICH OUTPUT. The backend output and the manifest are committed by the BACKEND stream.
The web and Android outputs are committed by the WEB and ANDROID streams, who run this script after
copying ``shared/``; ``--check`` holds an output to the inputs once it exists, and reports a missing
client output as "not generated yet" without failing, so the backend branch is not red for files that
belong to the other two.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "shared"
BACKEND_OUT = ROOT / "backend" / "app" / "shared_vocab.py"
WEB_ENUMS_OUT = ROOT / "frontend" / "lib" / "shared" / "enums.ts"
WEB_STRINGS_OUT = ROOT / "frontend" / "lib" / "strings" / "questionnaire.ts"
ANDROID_ENUMS_OUT = ROOT / "android" / "app" / "src" / "main" / "java" / "com" / "fieldrepository" / "app" / "data" / "SharedEnums.kt"
ANDROID_STRINGS_OUT = ROOT / "android" / "app" / "src" / "main" / "res" / "values" / "strings_questionnaire.xml"
MANIFEST = SHARED / "manifest.json"
PRISMA = ROOT / "backend" / "prisma" / "schema.prisma"
CLIENT_OUTPUTS = (WEB_ENUMS_OUT, WEB_STRINGS_OUT, ANDROID_ENUMS_OUT, ANDROID_STRINGS_OUT)
HEADER = "GENERATED by scripts/generate_shared.py from shared/. Do not edit; edit shared/ and regenerate."
_PLACEHOLDER = re.compile(r"\{([A-Za-z][A-Za-z0-9]*)\}")


def _load(name: str) -> dict:
    return json.loads((SHARED / name).read_text(encoding="utf-8"))


def _snake(key: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", key).lower()


def _py_literal(values: list[str]) -> str:
    return "(" + ", ".join(json.dumps(v, ensure_ascii=False) for v in values) + ("," if len(values) == 1 else "") + ")"


def backend_vocab(enums: dict, languages: dict) -> str:
    lines = [f'"""{HEADER}"""', "", "from __future__ import annotations", ""]
    lines.append(f"ENUMS_VERSION = {enums['version']}")
    lines.append(f"LANGUAGES_VERSION = {languages['version']}")
    lines.append("")
    for name, values in enums["enums"].items():
        lines.append(f"{name}: tuple[str, ...] = {_py_literal(values)}")
    lines.append("")
    lines.append(f"ESTIMATED_CAPTURED_AT_SOURCES: tuple[str, ...] = {_py_literal(enums['estimatedCapturedAtSources'])}")
    lines.append("")
    lines.append("LANGUAGE_LABELS: dict[str, str] = {")
    for lang in languages["languages"]:
        lines.append(f"    {json.dumps(lang['code'])}: {json.dumps(lang['label'], ensure_ascii=False)},")
    lines.append("}")
    lines.append("")
    lines.append("LANGUAGE_ALIASES: dict[str, str] = {")
    for alias, code in languages["aliases"].items():
        lines.append(f"    {json.dumps(alias, ensure_ascii=False)}: {json.dumps(code)},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def web_enums(enums: dict, languages: dict) -> str:
    lines = [f"// {HEADER}", ""]
    for name, values in enums["enums"].items():
        literal = ", ".join(json.dumps(v) for v in values)
        lines.append(f"export const {name}Values = [{literal}] as const;")
        lines.append(f"export type {name} = (typeof {name}Values)[number];")
        lines.append("")
    est = ", ".join(json.dumps(v) for v in enums["estimatedCapturedAtSources"])
    lines.append(f"export const EstimatedCapturedAtSources: readonly CapturedAtSource[] = [{est}];")
    lines.append("")
    lines.append("export const Languages: ReadonlyArray<{ code: string; label: string }> = [")
    for lang in languages["languages"]:
        lines.append(f"  {{ code: {json.dumps(lang['code'])}, label: {json.dumps(lang['label'], ensure_ascii=False)} }},")
    lines.append("];")
    lines.append("")
    lines.append("export const LanguageAliases: Readonly<Record<string, string>> = {")
    for alias, code in languages["aliases"].items():
        lines.append(f"  {json.dumps(alias, ensure_ascii=False)}: {json.dumps(code)},")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def _kotlin_name(value: str) -> str:
    return value if re.match(r"^[A-Z][A-Z0-9_]*$", value) else _snake(value).upper()


def android_enums(enums: dict, languages: dict) -> str:
    lines = [f"// {HEADER}", "package com.fieldrepository.app.data", ""]
    for name, values in enums["enums"].items():
        lines.append(f"enum class {name}(val wire: String) {{")
        body = [f"    {_kotlin_name(v)}({json.dumps(v)})" for v in values]
        lines.append(",\n".join(body) + ";")
        lines.append("")
        lines.append("    companion object {")
        lines.append(f"        fun fromWire(value: String?): {name}? = entries.firstOrNull {{ it.wire == value }}")
        lines.append("    }")
        lines.append("}")
        lines.append("")
    lines.append("object SharedLanguages {")
    lines.append("    val labels: Map<String, String> = linkedMapOf(")
    lines.append(",\n".join(f"        {json.dumps(l['code'])} to {json.dumps(l['label'], ensure_ascii=False)}" for l in languages["languages"]))
    lines.append("    )")
    lines.append("    val aliases: Map<String, String> = mapOf(")
    lines.append(",\n".join(f"        {json.dumps(a, ensure_ascii=False)} to {json.dumps(c)}" for a, c in languages["aliases"].items()))
    lines.append("    )")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def web_strings(strings: dict) -> str:
    lines = [f"// {HEADER}", ""]
    lines.append("export const questionnaireStrings = {")
    for key, text in strings["strings"].items():
        names = list(dict.fromkeys(_PLACEHOLDER.findall(text)))
        if names:
            params = ", ".join(f"{n}" for n in names)
            typed = "; ".join(f"{n}: string | number" for n in names)
            body = _PLACEHOLDER.sub(lambda m: "${" + m.group(1) + "}", text.replace("\\", "\\\\").replace("`", "\\`"))
            lines.append(f"  {key}: ({{ {params} }}: {{ {typed} }}): string => `{body}`,")
        else:
            lines.append(f"  {key}: {json.dumps(text, ensure_ascii=False)},")
    lines.append("} as const;")
    lines.append("")
    lines.append("export type QuestionnaireStringKey = keyof typeof questionnaireStrings;")
    lines.append("")
    return "\n".join(lines)


def _android_text(text: str) -> str:
    order: list[str] = []
    for name in _PLACEHOLDER.findall(text):
        if name not in order:
            order.append(name)
    escaped = escape(text).replace("'", "\\'").replace('"', '\\"').replace("%", "%%")
    if text.startswith("@") or text.startswith("?"):
        escaped = "\\" + escaped
    return _PLACEHOLDER.sub(lambda m: f"%{order.index(m.group(1)) + 1}$s", escaped)


def android_strings(strings: dict) -> str:
    lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
    for key, text in strings["strings"].items():
        formatted = "" if _PLACEHOLDER.search(text) else ' formatted="false"' if "%" in text else ""
        lines.append(f'    <string name="q_{_snake(key)}"{formatted}>{_android_text(text)}</string>')
    lines.append("</resources>")
    lines.append("")
    return "\n".join(lines)


# The files BUILD_PLAN section 0.1 shares byte-for-byte across the three streams. Older shared files
# (the artisan form contract and friends) have their own enforcing tests and are left out, so an edit
# to one of them on another branch does not turn this manifest stale.
MANIFEST_FILES = (
    "enums.json",
    "languages.json",
    "questionnaire-contract.json",
    "questionnaire-form-contract.json",
    "session-title.json",
    "strings/questionnaire.json",
)


def digest(path: Path) -> str:
    """sha256 of the file with CRLF read as LF: a Windows checkout (core.autocrlf) holds the same
    blob as Linux CI, and the manifest must say so on both."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def manifest() -> str:
    files = {name: digest(SHARED / name) for name in MANIFEST_FILES}
    return json.dumps({"generatedBy": "scripts/generate_shared.py", "sha256": files}, indent=2) + "\n"


def prisma_drift(enums: dict) -> list[str]:
    """Every Prisma enum that shares a name with shared/enums.json must have exactly its values."""
    if not PRISMA.exists():
        return []
    text = PRISMA.read_text(encoding="utf-8")
    problems = []
    for match in re.finditer(r"^enum\s+(\w+)\s*\{(.*?)^\}", text, re.MULTILINE | re.DOTALL):
        name, body = match.group(1), match.group(2)
        if name not in enums["enums"]:
            continue
        values = [line.split("//")[0].strip() for line in body.splitlines()]
        values = [v for v in values if v and not v.startswith("@")]
        if values != enums["enums"][name]:
            problems.append(f"schema.prisma enum {name} is {values}, shared/enums.json says {enums['enums'][name]}")
    return problems


def outputs() -> dict[Path, str]:
    enums, languages, strings = _load("enums.json"), _load("languages.json"), _load("strings/questionnaire.json")
    return {
        BACKEND_OUT: backend_vocab(enums, languages),
        WEB_ENUMS_OUT: web_enums(enums, languages),
        ANDROID_ENUMS_OUT: android_enums(enums, languages),
        WEB_STRINGS_OUT: web_strings(strings),
        ANDROID_STRINGS_OUT: android_strings(strings),
    }


def main(argv: list[str]) -> int:
    check = "--check" in argv
    only_backend = "--backend-only" in argv
    produced = outputs()
    if not check:
        for path, text in produced.items():
            if only_backend and path in CLIENT_OUTPUTS:
                continue
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        MANIFEST.write_text(manifest(), encoding="utf-8", newline="\n")
        print(f"wrote {len(produced) - (len(CLIENT_OUTPUTS) if only_backend else 0)} outputs and shared/manifest.json")
        return 0
    stale: list[str] = []
    for path, text in produced.items():
        rel = path.relative_to(ROOT).as_posix()
        if not path.exists():
            if path in CLIENT_OUTPUTS:
                print(f"not generated yet (the owning stream runs this script): {rel}")
                continue
            stale.append(f"missing: {rel}")
        elif path.read_text(encoding="utf-8") != text:
            stale.append(f"stale: {rel}")
    if not MANIFEST.exists() or MANIFEST.read_text(encoding="utf-8") != manifest():
        stale.append("stale: shared/manifest.json")
    stale.extend(prisma_drift(_load("enums.json")))
    for line in stale:
        print(line)
    if stale:
        print("Run: python scripts/generate_shared.py")
        return 1
    print("shared outputs are current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
