def fetch(cache: pathlib.Path, fetch_now: bool) -> tuple[list, list, list]:
    cache.mkdir(parents=True, exist_ok=True)

    def grab(name: str, url: str, unzip_member: str | None = None) -> pathlib.Path:
        path = cache / name
        if path.exists() and not fetch_now:
            return path
        if path.exists():
            return path
        print(f"  downloading {name} …", flush=True)
        raw = urllib.request.urlopen(url, timeout=600).read()
        if unzip_member:
            with zipfile.ZipFile(io.BytesIO(raw)) as archive:
                raw = archive.read(unzip_member)
        path.write_bytes(raw)
        return path

    districts = grab("districts.geojson", DISTRICTS_URL, unzip_member="output.geojson")
    states = grab("states.geojson", STATES_URL)
    country = grab("india-osm.geojson", COUNTRY_URL)
    load = lambda p: json.loads(p.read_text(encoding="utf-8"))["features"]  # noqa: E731
    return load(districts), load(states), load(country)


# ---------------------------------------------------------------------------------------------
# Point-in-polygon, used only to attribute and to verify
# ---------------------------------------------------------------------------------------------


def polygons_of(geometry: dict) -> list:
    kind = geometry["type"]
    if kind == "Polygon":
        return [geometry["coordinates"]]
    if kind == "MultiPolygon":
        return geometry["coordinates"]
    return []


def ring_contains(ring: list, x: float, y: float) -> bool:
    inside = False
    count = len(ring)
    for i in range(count):
        x1, y1 = ring[i][0], ring[i][1]
        x2, y2 = ring[(i + 1) % count][0], ring[(i + 1) % count][1]
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) / (y2 - y1) * (x2 - x1):
            inside = not inside
    return inside


def features_contain(features: list, x: float, y: float) -> bool:
    for feature in features:
        for polygon in polygons_of(feature["geometry"]):
            if polygon and ring_contains(polygon[0], x, y) and not any(
                ring_contains(hole, x, y) for hole in polygon[1:]
            ):
                return True
    return False


def sampled(geometry: dict, per_ring: int = 25) -> list:
    out: list = []
    for polygon in polygons_of(geometry):
        if polygon:
            ring = polygon[0]
            out += ring[:: max(1, len(ring) // per_ring)]
    return out or [[0.0, 0.0]]


# ---------------------------------------------------------------------------------------------
# Attribution: the register decides, geometry may veto
# ---------------------------------------------------------------------------------------------


def attribute(districts: list, states: list) -> tuple[dict, list, list, list]:
    by_state: dict[str, list] = collections.defaultdict(list)
    for feature in states:
        raw = feature["properties"]["ST_NM"]
        name = GEO_STATE_ALIASES.get(raw) or canonical_state(raw)
        if name:
            by_state[name].append(feature)

    def overlap(geometry: dict, state: str) -> float | None:
        polys = by_state.get(state)
        if not polys:
            return None
        points = sampled(geometry)
        cx = sum(p[0] for p in points) / len(points)
        cy = sum(p[1] for p in points) / len(points)
        # Nudged 10% toward the centroid so a vertex sitting exactly ON the shared border, which is
        # every vertex of a border segment, is judged by which side the district actually occupies.
        hits = sum(
            1
            for p in points
            if features_contain(polys, p[0] + (cx - p[0]) * 0.10, p[1] + (cy - p[1]) * 0.10)
        )
        return hits / len(points)

    def geometric_state(geometry: dict) -> str | None:
        points = sampled(geometry)
        cx = sum(p[0] for p in points) / len(points)
        cy = sum(p[1] for p in points) / len(points)
        for state, polys in by_state.items():
            if features_contain(polys, cx, cy):
                return state
        best, winner = 0, None
        for state in by_state:
            score = overlap(geometry, state) or 0
            if score > best:
                best, winner = score, state
        return winner

    resolved: dict[tuple[str, str], dict] = {}
    # THE STATE OF *EVERY* POLYGON, whether or not the register has a district for it.
    #
    # These are two different questions and conflating them deleted real borders. The register join
    # keys a district to app data and is allowed to fail; drawing a BORDER needs only to know which
    # state each side of an edge belongs to, and must never fail. Dropping the three polygons the
    # register cannot name — Delhi's Shahdara, and Mirpur and Muzaffarabad, which lie inside the
    # national border but which the LGD register does not enumerate — left their shared edges counted
    # ONCE instead of twice, so the classifier read them as coast and deleted them. The J&K/PoK
    # internal borders vanished, silently, from a pass whose whole purpose is not to lose geometry.
    owner_state: list[tuple[dict, str]] = []
    vetoed, unresolved = [], []
    for feature in districts:
        raw_name = feature["properties"].get("dtname") or ""
        claims = [
            (state, resolved_name)
            for state in INDIAN_STATES_AND_UNION_TERRITORIES
            if (resolved_name := canonical_district(state, raw_name))
        ]
        elsewhere = geometric_state(feature["geometry"])
        if not claims:
            unresolved.append((raw_name, elsewhere))
            if elsewhere:
                owner_state.append((feature, elsewhere))
            continue
        scored = sorted(
            ((overlap(feature["geometry"], s), s, d) for s, d in claims),
            key=lambda row: -1.0 if row[0] is None else row[0],
            reverse=True,
        )
        best, state, district = scored[0]
        contradicted = (
            best is not None and best <= 0.02 and elsewhere and elsewhere != state and elsewhere in by_state
        )
        if contradicted:
            vetoed.append((raw_name, state, district, elsewhere, round(best, 3)))
            if elsewhere:
                owner_state.append((feature, elsewhere))
            continue
        resolved[(state, district)] = feature
        owner_state.append((feature, state))
    return resolved, owner_state, vetoed, unresolved


# ---------------------------------------------------------------------------------------------
# The decomposition: interior edges, classified and chained into polylines
# ---------------------------------------------------------------------------------------------

Point = tuple[float, float]


def classify_edges(owner_state: list) -> tuple[dict[tuple[Point, Point], set], int]:
    """Every undirected edge -> the set of states whose districts use it. Plus the once-only count.

    Fed EVERY polygon with its state, not just the register-joined ones — see ``attribute``. An edge
    whose other side was dropped would be counted once and mistaken for the coast.
    """
    owners: dict[tuple[Point, Point], set] = collections.defaultdict(set)
    counts: collections.Counter = collections.Counter()
    for feature, state in owner_state:
        for polygon in polygons_of(feature["geometry"]):
            for ring in polygon:
                for i in range(len(ring) - 1):
                    a = (round(ring[i][0], 7), round(ring[i][1], 7))
                    b = (round(ring[i + 1][0], 7), round(ring[i + 1][1], 7))
                    if a == b:
                        continue
                    key = (a, b) if a <= b else (b, a)
                    owners[key].add(state)
                    counts[key] += 1
    frontier = sum(1 for key, n in counts.items() if n == 1)
    # Edges used once are the coast or the international frontier. The national outline draws those.
    for key, n in list(counts.items()):
        if n == 1:
            owners.pop(key, None)
    return owners, frontier


def chain(edges: set) -> list[list[Point]]:
    """Join edges end-to-end into the longest polylines they form.

    Chaining before simplifying is what keeps the output small: a polyline is one record with one
    delta run, and Douglas-Peucker can only remove a point if it can see its neighbours — an edge on
    its own has none to remove.
    """
    adjacency: dict[Point, list[Point]] = collections.defaultdict(list)
    for a, b in edges:
        adjacency[a].append(b)
        adjacency[b].append(a)
    unused = set(edges)
    lines: list[list[Point]] = []

    def take(a: Point, b: Point) -> bool:
        key = (a, b) if a <= b else (b, a)
        if key in unused:
            unused.discard(key)
            return True
        return False

    # Start from junctions and dead ends first, so a chain is not cut arbitrarily mid-run.
    starts = [p for p, n in adjacency.items() if len(n) != 2] or list(adjacency)
    for start in starts + list(adjacency):
        for first in adjacency[start]:
            if not take(start, first):
                continue
            line = [start, first]
            cursor = first
            while True:
                nxt = next((p for p in adjacency[cursor] if take(cursor, p)), None)
                if nxt is None:
                    break
                line.append(nxt)
                cursor = nxt
            lines.append(line)
    return lines


def simplify(line: list[Point], tolerance: float) -> list[Point]:
    """Douglas-Peucker, with the two ends and the four extremes pinned.

    Pinning the extremes is not a nicety — the national outline's own provenance note records that a
    plain tolerance sweep deleted Indira Point and the western tip, silently shortening the country.
    """
    if len(line) < 3:
        return line
    keep = {0, len(line) - 1}
    for pick in (min, max):
        keep.add(pick(range(len(line)), key=lambda i: line[i][0]))
        keep.add(pick(range(len(line)), key=lambda i: line[i][1]))

    def walk(lo: int, hi: int) -> None:
        if hi <= lo + 1:
            return
        x1, y1 = line[lo]
        x2, y2 = line[hi]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy)
        worst, index = -1.0, lo
        for i in range(lo + 1, hi):
            px, py = line[i]
            d = (
                abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
                if norm
                else math.hypot(px - x1, py - y1)
            )
            if d > worst:
                worst, index = d, i
        if worst > tolerance:
            keep.add(index)
            walk(lo, index)
            walk(index, hi)

    sys.setrecursionlimit(max(sys.getrecursionlimit(), len(line) * 2 + 1000))
    walk(0, len(line) - 1)
    return [line[i] for i in sorted(keep)]


