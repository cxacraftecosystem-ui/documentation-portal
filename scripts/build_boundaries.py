#!/usr/bin/env python3
"""Build the state and district BORDER geometry both apps draw, from published sources.

Run me from the repo root:

    backend/.venv/Scripts/python.exe scripts/build_boundaries.py --fetch

WHY THIS SCRIPT IS COMMITTED AND THE NATIONAL OUTLINE'S GENERATOR WAS NOT
------------------------------------------------------------------------
``frontend/components/map/indiaGeometry.ts`` says it was "regenerated by the script in the stream-2
scratchpad". That script is gone, so the only way to re-derive the outline is to reconstruct the
pipeline from its comments. This one lives in the repo so the next person can re-run it against a
newer district vintage — which is the whole point, since Indian districts change several times a year.

WHAT IT PRODUCES, AND WHY BORDERS RATHER THAN POLYGONS
------------------------------------------------------
The map draws PINS, not a choropleth. It needs the *lines* a reader recognises as borders, so that is
what this emits — and doing it that way is both smaller and more correct:

  * every interior border is stored ONCE. As polygons, the Rajasthan/Gujarat border is a ring segment
    in Rajasthan's polygon and the same segment reversed in Gujarat's. 86.4% of the source's edges are
    such pairs, so polygons would ship the interior of India twice.
  * the NATIONAL boundary is not emitted at all. It is already in the repo, verified point-in-polygon
    against the official depiction, and it is drawn ONCE by both apps at every detail level. That is
    what makes "the national boundary is the same for all three levels" true by construction rather
    than by hoping two published datasets agree — and they do NOT agree: measured against
    ``india-osm.geojson``, the district source's outer extent differs by up to ~0.02 degrees (~2 km).
    Interior borders are therefore CLIPPED to the national outline when drawn.

THE DECOMPOSITION, which is exact because the source is topologically clean
---------------------------------------------------------------------------
Two districts that share a border share the identical coordinate pairs, so an undirected edge tally
partitions every segment with no geometry library involved (measured on the 2025 source: 466,603 edges
shared by exactly two districts, 73,633 appearing once, and exactly one appearing four times):

    shared by two districts of DIFFERENT states -> a STATE border
    shared by two districts of the SAME state   -> a DISTRICT border
    appearing once                              -> the coast or the international frontier; DROPPED,
                                                   because the national outline already draws it

A consequence worth stating: state borders are derived from the DISTRICT source, not from the separate
states file. That is deliberate. It makes the two levels consistent with each other by construction,
and it is the only way Ladakh gets a border at all — every published states file still predates the
2019 split, so Ladakh is inside Jammu & Kashmir there, while the district source has Leh and Kargil.

SOURCES
-------
Both are fetched by ``--fetch`` and cached; pass ``--cache DIR`` to reuse a download.

  districts  kaggle.com/datasets/adityaradha007/indian-districts-geojson  (755 features, ``dtname``
             only — no state, which is why the state is derived below)
  states     datameet/maps ``docs/data/geojson/states.geojson``  (36 features, ``ST_NM``) — used ONLY
             to derive each district's state, never for its own geometry
  country    datameet/maps ``Country/india-osm.geojson`` — used ONLY to re-verify the depiction. It is
             byte-for-byte the source the shipped outline was built from (6,651,148 bytes).

HOW A DISTRICT IS ATTRIBUTED TO A STATE, and the trap in it
-----------------------------------------------------------
The register (``services.address``) decides; geometry may only VETO. A name-first join alone puts
Sikkim's pre-2021 districts — literally "East District", "North District", "South District", "West
District" — into Delhi, whose districts are East/North/South/West. A geometry-first join alone
misplaces enclaves (Puducherry's Yanam sits inside Andhra Pradesh) and border slivers. So: resolve the
name through the register, and reject only when the claimed state contains effectively NONE of the
polygon AND the polygon demonstrably lies in a different state that the states file does have. Low
overlap on its own is not evidence — two datasets' coastlines differ by ~2 km, so island and coastal
districts legitimately score near zero.

ENCODINGS — both already have decoders in the repo; do not invent a third
-------------------------------------------------------------------------
  web      the polyline scheme ``indiaGeometry.indiaRings`` decodes: zig-zag varints, five payload
           bits per character over an alphabet with nothing that needs escaping inside a TS string,
           coordinates delta-encoded at 3 decimal places.
  android  the ``IND1`` binary ``IndiaOutline.loadIndiaGeometry`` reads: magic, four float64 bounds,
           an int32 count, then per polyline an int32 length and uint16 x/y on a grid spanning the
           bounds.
  shapes   ``--shapes-bin`` (and every ``--shapes`` run) also writes ``res/raw/district_shapes.bin``,
           the Android coverage map's district POLYGONS, decoded from the committed
           ``district-shapes.json`` so the web and both apps fill exactly the same rings. Same uint16
           grid and the outline's bounds; header ``DSH1``, four float64 bounds, an int32 district
           count, then per district: uint32 lgd, uint16 stateLgd, uint16 x/y centroid, uint16 ring
           count, and per ring an int32 length and uint16 x/y pairs. Districts with no polygon are
           absent (the coverage payload's ``polygon: PARENT`` draws them inside their parent).
"""

