def android_outline_bounds() -> tuple[float, float, float, float]:
    """The bounds in ``res/raw/india_outline.bin``'s header.

    Android derives a world space from whichever bounds an asset declares, so every asset it draws
    together has to declare the SAME ones or the layers sit in slightly different spaces. The outline is
    the authority — it is the file the pins are projected through — so the borders adopt its header
    rather than a constant that happens to look like it.
    """
    blob = (ROOT / "android" / "app" / "src" / "main" / "res" / "raw" / "india_outline.bin").read_bytes()
    magic, min_lon, max_lon, min_lat, max_lat = struct.unpack_from(">idddd", blob, 0)
    if magic != OUTLINE_MAGIC:
        raise SystemExit("india_outline.bin: bad magic; refusing to guess the bounds")
    return min_lon, max_lon, min_lat, max_lat


def encode_web(lines: list[list[Point]]) -> str:
    """The scheme ``indiaGeometry.indiaRings`` decodes, minus the hole flag it has no use for here."""
    out: list[str] = []
    x = y = 0

    def varint(value: int) -> None:
        zig = (value << 1) ^ (value >> 31) if value < 0 else value << 1
        while True:
            chunk = zig & 0x1F
            zig >>= 5
            out.append(ALPHABET[chunk | (0x20 if zig else 0)])
            if not zig:
                return

    for line in lines:
        varint(len(line))
        for lon, lat in line:
            qx = round(lon * SCALE)
            qy = round(lat * SCALE)
            varint(qx - x)
            varint(qy - y)
            x, y = qx, qy
    return "".join(out)


def encode_android(lines: list[list[Point]], bounds: tuple[float, float, float, float]) -> bytes:
    """The ``IND1`` binary ``IndiaOutline.loadIndiaGeometry`` reads, one record per polyline."""
    min_lon, max_lon, min_lat, max_lat = bounds
    buf = io.BytesIO()
    buf.write(struct.pack(">i", OUTLINE_MAGIC))
    buf.write(struct.pack(">dddd", min_lon, max_lon, min_lat, max_lat))
    buf.write(struct.pack(">i", len(lines)))
    lon_step = (max_lon - min_lon) / QUANT_MAX
    lat_step = (max_lat - min_lat) / QUANT_MAX
    for line in lines:
        buf.write(struct.pack(">i", len(line)))
        for lon, lat in line:
            qx = min(QUANT_MAX, max(0, round((lon - min_lon) / lon_step)))
            qy = min(QUANT_MAX, max(0, round((lat - min_lat) / lat_step)))
            buf.write(struct.pack(">HH", qx, qy))
    return buf.getvalue()


