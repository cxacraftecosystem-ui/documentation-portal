/**
 * The outline of India, as the app draws it.
 *
 * PROVENANCE, which matters more here than in most modules. The source is DataMeet's
 * `Country/india-osm.geojson` — one MultiPolygon, `admin_level: 2` — which carries the OFFICIAL
 * Government of India depiction. That was not assumed; it was verified by point-in-polygon before
 * anything was simplified, and the same seven tests are re-run against the SIMPLIFIED geometry
 * below, because simplification is exactly what silently amputates a salient or drops an island
 * group. Aksai Chin, Gilgit-Baltistan and Muzaffarabad are INSIDE; Lhasa and Karachi are OUTSIDE;
 * the northern extent reaches 37.0820N, which is what proves the outline is not clipped at the Line
 * of Control (~35.5N), and the southern extent reaches 6.7560N at Indira Point, which is what
 * proves the Nicobars survived.
 *
 * Most Western datasets — Natural Earth, world-atlas TopoJSON, raw OSM extracts — do NOT use this
 * depiction. Never substitute one for this file because it is smaller or easier to fetch.
 *
 * WHY IT IS A STRING AND NOT GEOJSON. The source is 6,651,148 bytes. Douglas-Peucker at
 * 0.012 degrees, quantised to 3 decimal places, and delta-encoded leaves 18.3 KiB —
 * small enough to be part of a page rather than a fetch, with no loading state, no second network
 * failure mode, and no mapping library. The encoding is the ordinary polyline scheme (zig-zag
 * varints, five payload bits per character) over an alphabet with no character that needs escaping
 * inside a TypeScript string.
 *
 * WHAT SIMPLIFICATION COST. All 307 polygons and all 308 rings survive — nothing is dropped
 * on grounds of size, because the smallest rings here are Lakshadweep. 95 rings that are
 * narrower than the tolerance itself are kept as their bounding box, which is their true extent and
 * the smallest honest stand-in for a shape there is no room left to describe. Point count falls
 * from 245,160 to 5,677.
 *
 * Regenerated by the script in the stream-2 scratchpad; if the tolerance ever changes, re-run the
 * seven tests before shipping.
 */

