export type Ring = Array<[number, number]>;
/** One polygon: its outer ring first, then any holes. India's geometry has exactly one hole. */
export type Polygon = Ring[];

let decoded: Polygon[] | null = null;

/**
 * The outline as rings of [longitude, latitude], decoded on first use and then kept.
 *
 * Decoding is a single pass over ~5,677 points and costs about a millisecond, which is why it
 * happens lazily rather than at module load: a route that imports this file for its types alone
 * should not pay for it, and the map pays it once.
 */
export function indiaRings(): Polygon[] {
  if (decoded) return decoded;
  const polygons: Polygon[] = [];
  let index = 0;
  let x = 0;
  let y = 0;

  const readInt = (): number => {
    let shift = 0;
    let result = 0;
    for (;;) {
      const value = VALUES.get(PAYLOAD[index++]) ?? 0;
      result |= (value & 0x1f) << shift;
      shift += 5;
      if (value < 0x20) break;
    }
    // Zig-zag: the low bit is the sign, so small negative deltas stay one character wide.
    return result & 1 ? ~(result >> 1) : result >> 1;
  };

  while (index < PAYLOAD.length) {
    const count = readInt();
    const isHole = readInt() !== 0;
    const ring: Ring = [];
    for (let n = 0; n < count; n += 1) {
      x += readInt();
      y += readInt();
      ring.push([x / SCALE, y / SCALE]);
    }
    ring.push(ring[0]);
    if (isHole && polygons.length) polygons[polygons.length - 1].push(ring);
    else polygons.push([ring]);
  }

  decoded = polygons;
  return polygons;
}
